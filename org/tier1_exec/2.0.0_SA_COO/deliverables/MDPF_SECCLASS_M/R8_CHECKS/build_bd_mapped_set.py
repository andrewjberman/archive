"""build_bd_mapped_set.py -- MDPF_SECCLASS BD forward fix 2 (CTO rulings batch 139): the explicit write set for the one-act writer.

From the 290-ticker census (R8_BD_290_CENSUS_20261002T0953Z.json) it writes BD_MAPPED_WRITE_SET_20261002.tsv, one row per ticker,
tab-separated: ticker, asset_class, sub_asset_class (may be empty), name, bd_pair, disposition. Three dispositions only:
  direct          -- the 28 whose bd-securities pair is already in the canonical vocabulary (written as the pair)
  class_kept      -- fixed_income / Investment Grade or Floating Rate, AFTER every name was read against fixed income
                     (batch 139); written fixed_income with no sub class. MISFITS below are excluded by name read.
  renamed         -- equity / Emerging Markets -> equity / EM
Everything else (the per-ticker group, the misfits, needs_review, no bd row, VMFXX and GOFXX) is NOT in the set.
"""
from __future__ import annotations

import json
from pathlib import Path

HERE = Path(__file__).resolve().parent
CENSUS = HERE / "R8_BD_290_CENSUS_20261002T0953Z.json"
OUT = HERE.parent / "BD_MAPPED_WRITE_SET_20261002.tsv"

# The name read of the 62 (2.0.0_SA_COO~M, 2026-10-02 10:2xZ): each is NOT a plain fixed income fund, so it moves to the
# per-ticker group (batch 139). Reason per ticker, as read from the custody name.
MISFITS = {
    "AAETX": "target-date allocation (American Funds 2030 Target Date)",
    "VTTHX": "target-date allocation (Vanguard Target Retirement 2030)",
    "VTTVX": "target-date allocation (Vanguard Target Retirement 2025)",
    "FTYPX": "target-date allocation (Fidelity Freedom Index 2055)",
    "TCOIX": "target-date allocation (Nuveen Lifecycle 2040)",
    "TRRJX": "target-date allocation (T. Rowe Price Retirement 2035)",
    "AWSHX": "US large-cap equity fund (American Funds Washington Mutual)",
    "MSSGX": "equity fund (Morgan Stanley Inst Inception)",
    "MPAIX": "equity fund (Morgan Stanley Inst Advantage)",
    "VTCLX": "equity fund (Vanguard Tax-Managed Capital Appreciation)",
    "CAIBX": "allocation, equity-heavy income (American Funds Capital Income Builder A)",
    "CFIHX": "allocation (Capital Income Builder F3)",
    "CIBCX": "allocation (Capital Income Builder C)",
    "AMECX": "allocation (American Funds Income Fund of America A)",
    "CIMAX": "allocation (Income Fund of America 529)",
    "FKIQX": "allocation (Franklin Income)",
    "DODBX": "balanced (Dodge & Cox Balanced)",
    "BALCX": "balanced (American Funds American Balanced C)",
    "AFMBX": "balanced (American Funds American Balanced F3)",
    "VWINX": "balanced (Vanguard Wellesley Income)",
    "LCFYX": "convertibles (Lord Abbett Convertible)",
    "LPXIX": "preferred securities (Cohen & Steers Low Duration Preferred & Income)",
    "NPSRX": "preferred securities (Nuveen Preferred Securities & Income)",
    "CPXIX": "preferred securities (Cohen & Steers Preferred Securities & Income)",
    "HPI": "preferred securities closed-end fund (John Hancock Preferred Income)",
    "PFF": "preferred securities ETF (iShares Preferred & Income)",
    "VRP": "preferred securities ETF (Invesco Variable Rate Preferred)",
    "USIG": "no custody name to read (blank)",
    "ABNFX": "seed row in fix 3 (fixed_income / Intermediate, peer AGG) -- one writer per ticker",
    "LBNOX": "share class of LBNYX (Lord Abbett Bond Debenture), whose seed row in fix 3 is High Yield",
}


def main() -> int:
    rows = json.loads(CENSUS.read_text(encoding="utf-8"))["rows"]
    out, counts = [], {"direct": [0, 0.0], "class_kept": [0, 0.0], "renamed": [0, 0.0], "misfit": [0, 0.0]}
    for r in rows:
        name = (r["bd_name"] or r["holding_name"] or r["ticker"]).strip()
        pair = "%s / %s" % (r["bd_asset_class"], r["bd_sub_asset_class"])
        if r["direct_match"]:
            disp, ac, sub = "direct", r["bd_asset_class"], r["bd_sub_asset_class"] or ""
        elif r["bd_asset_class"] == "fixed_income" and r["bd_sub_asset_class"] in ("Investment Grade", "Floating Rate"):
            if r["ticker"] in MISFITS:
                counts["misfit"][0] += 1
                counts["misfit"][1] += r["open_mv"]
                continue
            disp, ac, sub = "class_kept", "fixed_income", ""
        elif r["bd_asset_class"] == "equity" and r["bd_sub_asset_class"] == "Emerging Markets":
            disp, ac, sub = "renamed", "equity", "EM"
        else:
            continue
        counts[disp][0] += 1
        counts[disp][1] += r["open_mv"]
        out.append("\t".join([r["ticker"], ac, sub, name, pair, disp]))
    header = ("# MDPF_SECCLASS BD forward fix 2 (CTO rulings batch 139) -- generated by R8_CHECKS/build_bd_mapped_set.py from the 290 census.\n"
              "# Columns: ticker, asset_class, sub_asset_class (may be empty), name, bd-securities pair, disposition.\n")
    OUT.write_text(header + "\n".join(sorted(out)) + "\n", encoding="utf-8", newline="\n")
    for k, (n, mv) in counts.items():
        print("%-10s tickers=%3d open_mv=%14.2f" % (k, n, mv))
    print("rows written:", len(out), "->", OUT.name)
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
