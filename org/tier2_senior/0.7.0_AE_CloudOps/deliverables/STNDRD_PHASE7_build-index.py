from __future__ import annotations

# build-index.py -- generates docs/architecture/INDEX.md keyed by RESOURCE TYPE.
#
# OPAL_STNDRD phase 7 (axis F(ii)): the codename corpus (355 files at build) becomes
# navigable by what a reader OWNS (lambda / trigger / EC2 / terraform / bucket / portal /
# data-pipeline / comp-tools / governance), not by what an incident was called.
#
# INSTRUMENT, NOT PROSE (axis F(iv)): the index is GENERATED -- rerun this script after
# adding a doc; a hand edit of INDEX.md is drift by definition. Classification is a
# keyword scan of each file's head; a file matching nothing lands in UNCLASSIFIED
# (visible debt), and a file may appear under several types (readers overlap).
#
# Usage: python docs/architecture/build-index.py [--check]
#   --check: exit 2 if the committed INDEX.md differs from a fresh generation
#            (the drift arm; same announce-then-enforce class as the other Z1 gates).

import argparse
import io
import re
import sys
from pathlib import Path

DOCS = Path(__file__).resolve().parent
INDEX = DOCS / "INDEX.md"
HEAD_LINES = 50

TYPE_KEYWORDS = [
    ("Lambda", ("lambda",)),
    ("Triggers / scheduling", ("eventbridge", "scheduler", "cron(", "trigger", "absence-check")),
    ("EC2 / SSM", ("ec2", "ssm ", "ssm-", "instance")),
    ("Terraform / IAM", ("terraform", ".tf", "iam", "safe-apply")),
    ("S3 / buckets", ("s3://", "bucket", "bronze", "silver", "gold/")),
    ("Portal / frontend", ("portal", "frontend", "react", "cloudfront", "usequery")),
    ("Data pipelines", ("pipeline", "gold script", "etl", "ingest", "medallion")),
    ("Comp-tools / graph", ("comp-", "kuzu", "dependency graph", "globgrph")),
    ("Governance / process", ("protocol", "gate", "audit", "ledger", "ravc", "charter")),
]


def classify(text: str) -> list[str]:
    low = text.lower()
    return [t for t, kws in TYPE_KEYWORDS if any(k in low for k in kws)]


def title_of(text: str, fallback: str) -> str:
    for line in text.splitlines():
        if line.startswith("# "):
            return line[2:].strip()
    return fallback


def generate() -> str:
    files = sorted(p for p in DOCS.glob("*.md") if p.name != "INDEX.md")
    sections: dict[str, list[str]] = {t: [] for t, _ in TYPE_KEYWORDS}
    unclassified: list[str] = []
    for p in files:
        try:
            head = "".join(io.open(p, encoding="utf-8", errors="replace").readlines()[:HEAD_LINES])
        except OSError:
            head = ""
        title = re.sub(r"\s+", " ", title_of(head, p.stem))[:160]
        entry = "- `%s` -- %s" % (p.name, title)
        types = classify(head)
        if not types:
            unclassified.append(entry)
        for t in types:
            sections[t].append(entry)

    out = []
    out.append("# docs/architecture INDEX -- keyed by resource type")
    out.append("")
    out.append("> GENERATED by `docs/architecture/build-index.py` (OPAL_STNDRD phase 7, axis F). Do")
    out.append("> NOT hand-edit -- rerun the script after adding a doc; `--check` is the drift arm.")
    out.append("> A file may appear under several types (readers overlap); UNCLASSIFIED is visible")
    out.append("> debt, not an error.")
    out.append("")
    out.append("DENOMINATOR: %d file(s) indexed; %d unclassified." % (len(files), len(unclassified)))
    out.append("")
    for t, _ in TYPE_KEYWORDS:
        out.append("## %s (%d)" % (t, len(sections[t])))
        out.append("")
        out.extend(sections[t] or ["- (none)"])
        out.append("")
    out.append("## UNCLASSIFIED (%d)" % len(unclassified))
    out.append("")
    out.extend(unclassified or ["- (none)"])
    out.append("")
    return "\n".join(out)


def main() -> int:
    ap = argparse.ArgumentParser()
    ap.add_argument("--check", action="store_true")
    args = ap.parse_args()

    fresh = generate()
    if args.check:
        current = io.open(INDEX, encoding="utf-8").read() if INDEX.exists() else ""
        if current != fresh:
            print("DRIFT: INDEX.md != fresh generation -- rerun build-index.py")
            return 2
        print("OK: INDEX.md matches the corpus.")
        return 0
    io.open(INDEX, "w", encoding="utf-8", newline="\n").write(fresh)
    print("OK: wrote %s" % INDEX)
    return 0


if __name__ == "__main__":
    sys.exit(main())
