"""check_fa9_prefix.py -- acceptance arms for AMGT-fa-9 (the generated Lambda-safe prefix constant AI_FILL_GOLD_PREFIX).

  PYTHONPATH=<repo root> python check_fa9_prefix.py
Offline. Needs nothing of lib.research.aifill. The five existing constants and the registry hash must not move.
"""
from __future__ import annotations

import ast
import os
import subprocess
import sys

sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
import aifill_check_lib as L  # noqa: E402

REGISTRY_HASH = "fff9a273a59bc232addcd45968cfaca55832266e74e288512d5c61817d7c225e"
EXISTING = {
    "FILING_ATTEMPT_STATE_PREFIX": "amgt/harvest/state/filing_attempt/",
    "BLOOMBERG_BRONZE_PREFIX": "bloomberg/harvest/bronze/",
    "SEEKING_ALPHA_BRONZE_PREFIX": "seeking-alpha/harvest/bronze/",
    "BRIGHT_DATA_SERP_BRONZE_PREFIX": "bright-data/harvest/bronze/serp/",
    "SEEKING_ALPHA_JOB_RECORD_STATE_PREFIX": "seeking-alpha/harvest/state/job_record/",
}


def main():
    from lib.research.api import _harvest_prefixes as hp
    from lib.research.harvest import store as hstore

    arms = L.Arms("FA-9")
    arms.run("AI_FILL_GOLD_PREFIX equals the builder's table prefix", lambda: (getattr(hp, "AI_FILL_GOLD_PREFIX", None) == hstore.table_prefix("amgt", "gold", "ai_fill"), getattr(hp, "AI_FILL_GOLD_PREFIX", None)))
    arms.run("the five existing constants are unmoved", lambda: ([k for k, v in EXISTING.items() if getattr(hp, k, None) != v] == [], [k for k, v in EXISTING.items() if getattr(hp, k, None) != v]))
    arms.run("the registry hash is unmoved", lambda: (hp.REGISTRY_HASH == REGISTRY_HASH, hp.REGISTRY_HASH))

    def header_and_imports():
        src = open(hp.__file__, "r", encoding="utf-8").read()
        first = src.splitlines()[0]
        tree = ast.parse(src)
        imports = [n for n in ast.walk(tree) if isinstance(n, (ast.Import, ast.ImportFrom))]
        return first.startswith("# GENERATED by infra/aws/terraform/harvest/gen_harvest_prefixes.py") and "DO NOT EDIT" in first and not imports, first[:80]
    arms.run("the module is still marked GENERATED and imports nothing", header_and_imports)

    def generator_check():
        proc = subprocess.run([sys.executable, "infra/aws/terraform/harvest/gen_harvest_prefixes.py", "--check"], capture_output=True, text=True, timeout=120)
        return proc.returncode == 0 and "byte for byte" in proc.stdout, (proc.returncode, proc.stdout[-160:])
    arms.run("gen_harvest_prefixes.py --check exits 0 (the committed module is the generator's own output)", generator_check)

    def generator_has_entry():
        src = open("infra/aws/terraform/harvest/gen_harvest_prefixes.py", "r", encoding="utf-8").read()
        tree = ast.parse(src)
        for node in ast.walk(tree):
            if isinstance(node, ast.FunctionDef) and node.name == "compute":
                keys = [k.value for n in ast.walk(node) if isinstance(n, ast.Dict) for k in n.keys if isinstance(k, ast.Constant)]
                return "AI_FILL_GOLD_PREFIX" in keys and len(keys) == 6, keys
        return False, "no compute()"
    arms.run("compute() carries exactly six entries, the new one AI_FILL_GOLD_PREFIX", generator_has_entry)

    def sources_unchanged():
        src = open("infra/aws/terraform/harvest/gen_harvest_prefixes.py", "r", encoding="utf-8").read()
        return '_SOURCES = ("amgt", "bloomberg", "bright-data", "seeking-alpha")' in src, "_SOURCES moved"
    arms.run("the scoped sources tuple is unchanged", sources_unchanged)

    def test_pin():
        src = open("lib/research/api/tests/test_harvest_prefixes.py", "r", encoding="utf-8").read()
        return '"AI_FILL_GOLD_PREFIX"' in src and '_table_root("amgt", "harvest", "gold", "ai_fill")' in src, "the neighbouring test does not pin the new constant"
    arms.run("test_harvest_prefixes.py pins the new constant to fresh opal_naming output", test_pin)

    return arms.finish()


if __name__ == "__main__":
    sys.exit(main())
