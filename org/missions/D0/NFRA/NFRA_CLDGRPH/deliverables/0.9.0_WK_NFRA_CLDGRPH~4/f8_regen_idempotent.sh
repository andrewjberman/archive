#!/usr/bin/env bash
# F8-AC3 -- REGENERATED, NEVER HAND-EDITED.
#
# NFRA_CLDGRPH.TO-CG-F-8 / cell CG-s-28, 0.9.0_WK_NFRA_CLDGRPH~4.
#
# THREE CARRIERS, and the number of GENERATOR COMMANDS is MEASURED, not assumed: each carrier is
# asked which generator it declares in its own header, and the distinct set of those commands is
# what gets run. On this tree that set has TWO members, because .tools/gen_tool_registry.py writes
# BOTH org/modules/graph/TOOL_MASTER.yaml and .tools/tool_index.py in one invocation. The probe
# prints the measured count; it does not pad it to the carrier count.
#
# ALL COMPARISONS ARE ON LF-NORMALISED BYTES. This is an autocrlf checkout: .tools/tool_index.py
# is 543627 bytes in the worktree and 536980 at HEAD with IDENTICAL content, so a raw byte or
# `git status` comparison reports a phantom edit on every run.
set -u
cd "$(git rev-parse --show-toplevel)" || exit 1

timeout 240 python - <<'PY'
import difflib
import hashlib
import re
import subprocess
import sys

CARRIERS = ['.tools/TOOL_CLASSIFICATION.yaml',
            'org/modules/graph/TOOL_MASTER.yaml',
            '.tools/tool_index.py']

GEN_DECL = re.compile(r'(?:generated_by:\s*|GENERATED by\s+)(\S+?\.py)')


def read(p):
    with open(p, 'rb') as fh:
        return fh.read().replace(b'\r\n', b'\n')


def sha(b):
    return hashlib.sha256(b).hexdigest()[:16]


# ---- 1. WHICH generator does each carrier DECLARE? (read from the carrier, not assumed) --------
declared = {}
for c in CARRIERS:
    head = read(c)[:2000].decode('utf-8', 'replace')
    m = GEN_DECL.search(head)
    declared[c] = m.group(1) if m else '(UNDECLARED)'
    print('CARRIER %-40s declares generator %s' % (c, declared[c]))

cmds = []
for c in CARRIERS:
    g = declared[c]
    if g != '(UNDECLARED)' and g not in cmds:
        cmds.append(g)
print('')
print('REGEN_CARRIERS=%d' % len(CARRIERS))
print('REGEN_COMMANDS=%d  (MEASURED distinct generator command(s) across the %d carriers: %s -- '
      'gen_tool_registry.py writes TWO carriers in ONE invocation, so commands != carriers)'
      % (len(cmds), len(CARRIERS), ', '.join(cmds)))
print('')

before = {c: read(c) for c in CARRIERS}

# ---- 2. pass A ---------------------------------------------------------------------------------
for g in cmds:
    r = subprocess.run([sys.executable, g], capture_output=True, text=True)
    print('PASS_A  python %s  rc=%d' % (g, r.returncode))
    if r.returncode != 0:
        print(r.stdout[-2000:])
        print(r.stderr[-2000:])
        sys.exit(1)
after_a = {c: read(c) for c in CARRIERS}

# ---- 3. pass B ---------------------------------------------------------------------------------
for g in cmds:
    r = subprocess.run([sys.executable, g], capture_output=True, text=True)
    print('PASS_B  python %s  rc=%d' % (g, r.returncode))
    if r.returncode != 0:
        print(r.stdout[-2000:])
        print(r.stderr[-2000:])
        sys.exit(1)
after_b = {c: read(c) for c in CARRIERS}
print('')

# ---- 4. idempotence: pass B changed nothing pass A wrote ---------------------------------------
second_diff = 0
for c in CARRIERS:
    d = list(difflib.unified_diff(after_a[c].decode('utf-8', 'replace').splitlines(),
                                  after_b[c].decode('utf-8', 'replace').splitlines(),
                                  lineterm='', n=0))
    print('    %-40s passA sha %s  passB sha %s  diff_lines %d'
          % (c, sha(after_a[c]), sha(after_b[c]), len(d)))
    second_diff += len(d)
print('SECOND_REGEN_DIFF_LINES=%d' % second_diff)

# ---- 5. the W2-S30 control: was any carrier HAND-EDITED before this probe ran? -----------------
# A carrier is hand-edited iff its content AT PROBE START differs from what its own generator
# emits. That is the whole defect: a generated file that does not equal its generator's output.
hand = []
for c in CARRIERS:
    if before[c] != after_a[c]:
        d = list(difflib.unified_diff(before[c].decode('utf-8', 'replace').splitlines(),
                                      after_a[c].decode('utf-8', 'replace').splitlines(),
                                      lineterm='', n=0))
        hand.append((c, len(d)))
print('HAND_EDITED_CARRIERS=%d of %d%s'
      % (len(hand), len(CARRIERS),
         '' if not hand else ' -- ' + ', '.join('%s (%d diff lines)' % h for h in hand)))

# positive control on that comparator: a mutated copy MUST read as hand-edited
probe = bytearray(after_a[CARRIERS[0]])
probe[:0] = b'# f8 hand-edit control\n'
print('HAND_EDIT_CONTROL=%s -- an in-memory mutated copy of %s compares UNEQUAL to its '
      'generator output, so the 0 above is a measurement, not a constant'
      % ('FIRED' if bytes(probe) != after_a[CARRIERS[0]] else 'DID-NOT-FIRE', CARRIERS[0]))

rc = 0 if (second_diff == 0 and not hand) else 1
print('RC=%d' % rc)
sys.exit(rc)
PY
RC=$?
echo "PY_RC=${RC}"
exit ${RC}
