"""F10-AC3 -- DEPRECATED AT TOOL GRAIN, REGENERATED, NEVER HAND-EDITED.

REUSED, NOT REINVENTED: the three-carrier / measured-generator-command / LF-normalised idempotence
shape is F-8's (0.9.0_WK_NFRA_CLDGRPH~4, f8_regen_idempotent.sh) and is copied here under an f10_
name with its reasoning intact. WHY LF-NORMALISED: this is an autocrlf checkout, so a byte-identical
.tools/tool_index.py reads MODIFIED against HEAD and a raw byte compare reports a phantom edit on
every run.

ADDED HERE: the tool-grain lifecycle limbs -- the map's SCHEMA declares the field, the comp-aws
entry CARRIES it, the generated master ROW reads it, and population parity is unchanged (a
deprecated tool stays homed: 99 = 99).
"""

import difflib
import hashlib
import os
import re
import subprocess
import sys

import yaml

sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
import f10_lib as L  # noqa: E402

WS = L.WS
CARRIERS = ['.tools/TOOL_CLASSIFICATION.yaml',
            'org/modules/graph/TOOL_MASTER.yaml',
            '.tools/tool_index.py']
MAP = 'org/modules/graph/comp-coverage-map.yaml'
GEN_DECL = re.compile(r'(?:generated_by:\s*|GENERATED by\s+)(\S+?\.py)')


def read(p):
    with open(os.path.join(WS, p), 'rb') as fh:
        return fh.read().replace(b'\r\n', b'\n')


def sha(b):
    return hashlib.sha256(b).hexdigest()[:16]


print("F10-AC3 -- deprecated at tool grain, regenerated, never hand-edited")
print("")

# ---- 1. the SCHEMA declares the field ----------------------------------------------------------
doc = yaml.safe_load(read(MAP).decode('utf-8'))
field = ((doc.get('schema') or {}).get('node_fields') or {}).get('status')
declared = bool(field) and 'deprecated' in (field.get('values') or [])
entry = next((t for t in (doc.get('tools') or []) if t.get('tool') == 'comp-aws'), None)
entry_status = (entry or {}).get('status')
print("  map schema.node_fields.status  declared=%s  values=%s  default=%s"
      % (declared, (field or {}).get('values'), (field or {}).get('default')))
print("  map tools[comp-aws].status     = %r" % entry_status)
surface = next((s for s in (doc.get('surfaces') or []) if s.get('id') == 'AWS-CLOUD'), {})
print("  map surfaces[AWS-CLOUD].high_level_tool = %r" % surface.get('high_level_tool'))
print("MAP_STATUS_FIELD=%s"
      % ("deprecated (declared in schema)" if (declared and entry_status == 'deprecated')
         else "NOT-DECLARED-OR-NOT-CARRIED (declared=%s entry=%r)" % (declared, entry_status)))

# ---- 2. WHICH generator does each carrier DECLARE? (read from the carrier, not assumed) --------
declared_gen = {}
for c in CARRIERS:
    head = read(c)[:2000].decode('utf-8', 'replace')
    m = GEN_DECL.search(head)
    declared_gen[c] = m.group(1) if m else '(UNDECLARED)'
    print("  CARRIER %-40s declares generator %s" % (c, declared_gen[c]))
cmds = []
for c in CARRIERS:
    g = declared_gen[c]
    if g != '(UNDECLARED)' and g not in cmds:
        cmds.append(g)
print("  REGEN_CARRIERS=%d  REGEN_COMMANDS=%d (MEASURED distinct generator(s): %s -- "
      "gen_tool_registry.py writes TWO carriers in ONE invocation)"
      % (len(CARRIERS), len(cmds), ', '.join(cmds)))
print("")

before = {c: read(c) for c in CARRIERS}

for label, store in (('PASS_A', {}), ('PASS_B', {})):
    for g in cmds:
        r = subprocess.run([sys.executable, g], capture_output=True, text=True, cwd=WS)
        print("  %s  python %s  rc=%d" % (label, g, r.returncode))
        if r.returncode != 0:
            print(r.stdout[-1500:])
            print(r.stderr[-1500:])
            sys.exit(1)
    for c in CARRIERS:
        store[c] = read(c)
    if label == 'PASS_A':
        after_a = store
    else:
        after_b = store
print("")

# ---- 3. the generated MASTER row + population parity -------------------------------------------
master = yaml.safe_load(after_a['org/modules/graph/TOOL_MASTER.yaml'].decode('utf-8'))
row_status = (master.get('tools') or {}).get('comp-aws', {}).get('status')
counts = master.get('counts') or {}
n_master = counts.get('tools')
n_auth = counts.get('population_authority_count')
homed = 'comp-aws' in (master.get('tools') or {})
print("  TOOL_MASTER.yaml tools[comp-aws].status = %r   comp-aws STILL HOMED = %s"
      % (row_status, homed))
print("MASTER_ROW_STATUS=%s" % (row_status or 'ABSENT'))
print("PARITY=%s of %s   (a deprecated tool STAYS in the population -- membership unchanged)"
      % (n_master, n_auth))

# ---- 4. idempotence ----------------------------------------------------------------------------
second_diff = 0
for c in CARRIERS:
    d = list(difflib.unified_diff(after_a[c].decode('utf-8', 'replace').splitlines(),
                                  after_b[c].decode('utf-8', 'replace').splitlines(),
                                  lineterm='', n=0))
    print("    %-40s passA sha %s  passB sha %s  diff_lines %d"
          % (c, sha(after_a[c]), sha(after_b[c]), len(d)))
    second_diff += len(d)
print("SECOND_REGEN_DIFF_LINES=%d" % second_diff)

# ---- 5. the W2-S30 control: was any carrier HAND-EDITED before this probe ran? -----------------
hand = []
for c in CARRIERS:
    if before[c] != after_a[c]:
        d = list(difflib.unified_diff(before[c].decode('utf-8', 'replace').splitlines(),
                                      after_a[c].decode('utf-8', 'replace').splitlines(),
                                      lineterm='', n=0))
        hand.append((c, len(d)))
print("HAND_EDITED_CARRIERS=%d of %d%s"
      % (len(hand), len(CARRIERS),
         '' if not hand else ' -- ' + ', '.join('%s (%d diff lines)' % h for h in hand)))
probe = bytearray(after_a[CARRIERS[0]])
probe[:0] = b'# f10 hand-edit control\n'
print("HAND_EDIT_CONTROL=%s -- an in-memory mutated copy of %s compares UNEQUAL to its generator "
      "output, so the 0 above is a measurement, not a constant"
      % ('FIRED' if bytes(probe) != after_a[CARRIERS[0]] else 'DID-NOT-FIRE', CARRIERS[0]))

ok = (declared and entry_status == 'deprecated' and row_status == 'deprecated'
      and homed and n_master == n_auth and second_diff == 0 and not hand)
print("RC=%d" % (0 if ok else 1))
sys.exit(0 if ok else 1)
