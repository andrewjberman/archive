#!/bin/bash
# E1-AC6 -- the commit gate over EVERY Python file THIS task order touches, plus the thin-client
# battery whose refusal of `--mode` is the property the retired routes now point away from.
#
# THE LIST IS THE ORDER'S OWN EDIT SET, WRITTEN DOWN, not `git status`. A gate fed by the change
# set can only certify what changed; this order's claim is about a NAMED population, so the names
# are transcribed. If the two ever diverge, THAT is the finding.
#
# NOT IN THE LIST, AND WHY -- a gate list is not a change log, and an unstated omission is the
# defect this note exists to prevent:
#   .tools/tool_index.py  -- E1-AC3's dirty carrier. It is a GENERATED artifact ("GENERATED by
#     .tools/gen_tool_registry.py -- DO NOT EDIT", :1) and this order did NOT edit it. Its SOURCE
#     for the six help texts is graph-call-manifest.yaml, which this order DID edit; the compiled
#     index cannot be regenerated in this worktree because gen_tool_registry.py refuses on a
#     PRE-EXISTING population divergence (measured at HEAD: authority=99, classification=85, four
#     names in the classification absent from the authority). Filed as a BLOCKING surprise row.
#   .tools/comp-describe, .tools/comp-cluster -- bash shims, not Python. commit-gate.sh dispatches
#     by SUFFIX and would refuse them; they are syntax-checked with `bash -n` below, each with its
#     own printed verdict, rather than handed to a gate that cannot see them.
#   .tools/comp-which -- a Python file with NO .py suffix (a shebang tool on PATH). Same suffix
#     problem, so it is byte-compiled explicitly below. An unchecked file that produces rc=0 is
#     exactly what this note prevents.
#   .tools/TOOL_CLASSIFICATION.yaml, the three registry YAMLs, the manifest -- not Python.
#
# Exit: 0 = gate clean on every Python file AND the thin-client battery PASS; 1 = either failed;
#       2 = BLOCKED (a named file is absent -- a gate cannot certify a file it never read).
set -u
cd "$(git rev-parse --show-toplevel)" || exit 2

FILES="
org/modules/graph/comp_aws_cli.py
org/modules/graph/debtscan/comp_similar.py
.tools/gen_tool_classification.py
"

SUFFIXLESS_PY=".tools/comp-which"
SHELL_SHIMS=".tools/comp-describe .tools/comp-cluster"

N=0
for f in $FILES $SUFFIXLESS_PY $SHELL_SHIMS; do
  if [ ! -f "$f" ]; then
    echo "BLOCKED: $f is absent -- the gate cannot certify a file it never read"
    exit 2
  fi
  N=$((N + 1))
done
echo "commit_gate_all.sh: population $N file(s) -- 3 .py to commit-gate.sh, 1 suffix-less python, 2 bash shims"

# shellcheck disable=SC2086
bash .tools/commit-gate.sh $FILES
GATE_RC=$?

echo "commit_gate_all.sh: suffix-less python checked separately: $SUFFIXLESS_PY"
python -c "import py_compile; py_compile.compile('.tools/comp-which', doraise=True); print('  .tools/comp-which compiles')"
CW_RC=$?

SH_RC=0
for f in $SHELL_SHIMS; do
  if bash -n "$f"; then
    echo "  $f parses (bash -n)"
  else
    echo "  $f FAILED bash -n"
    SH_RC=1
  fi
done

echo ""
echo "commit_gate_all.sh: thin-client battery -- the client's REFUSAL of --mode is the property"
echo "  the retired routes now point away from, so it is quoted here rather than asserted:"
timeout 300 python .tools/tests/test_cg6_thin_client_battery.py 2>&1 | sed 's/^/  | /'
BATTERY_RC=${PIPESTATUS[0]}
echo "  thin-client battery rc=$BATTERY_RC"

if [ "$GATE_RC" -eq 0 ] && [ "$CW_RC" -eq 0 ] && [ "$SH_RC" -eq 0 ] && [ "$BATTERY_RC" -eq 0 ]; then
  echo "pre-commit gate clean ($N of $N file(s): commit-gate rc=0, comp-which compile rc=0, bash -n rc=0; thin-client battery PASS)"
  exit 0
fi
echo "pre-commit gate NOT clean: commit-gate.sh rc=$GATE_RC, comp-which rc=$CW_RC, bash -n rc=$SH_RC, battery rc=$BATTERY_RC"
exit 1
