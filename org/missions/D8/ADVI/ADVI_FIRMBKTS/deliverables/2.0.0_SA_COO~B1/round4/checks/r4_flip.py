"""ADVI_FIRMBKTS round 4 check for cell FB-g-1 (the flip rehearsal), issuer 2.0.0_SA_COO~B1.

Rehearses act 4's VALUE FLIP in a scratch copy of the registry: the 49financial scope's routed bucket alias
(`opal-data-bd`, routed=true) loses its routed marker, so lib/opal_naming.py `_routed_bucket()` returns the scope's own
bucket. Every generated target is then regenerated into a scratch directory and diffed against the checkout's bytes.
Nothing under the checkout is written; the registry copy lives in a temp directory.

--arms flip   grades the rehearsal (4 arms) and prints one line per target that changes and the lines that change.
Plain ASCII output; the last line carries the arm count.
"""
import argparse
import difflib
import json
import os
import shutil
import subprocess
import sys
import tempfile

SCOPE = "49financial"
ALIAS = "opal-data-bd"
# the targets the CTO's list names as readers of the routed bucket (round-3 analysis section 3 item 1, ADDENDUM 7)
READERS = (
    "infra/aws/lambda-edge/_shared/firm-config.mjs",
    "data/firm_registry.json",
    "data/assets/scripts/gold/investor_reporting/directory_runner.py",
    "data/assets/scripts/gold/investor_reporting/holdings_snapshot.py",
    "data/assets/scripts/gold/runners_49f/perfrp_firm_pin.py",
)


def _root(arg):
    if arg:
        return arg
    return subprocess.run(["git", "rev-parse", "--show-toplevel"], capture_output=True, text=True).stdout.strip()


EXPECTED = {
    "data/firm_registry.json",
    "infra/aws/lambda-edge/_shared/firm-config.mjs",
    "data/assets/scripts/gold/investor_reporting/directory_runner.py",
    "data/assets/scripts/gold/investor_reporting/holdings_snapshot.py",
    "data/black_diamond/scripts/bronze/_asset_dim_rest_pin.py",
}
OLD, NEW = "opal-data-bd", "opal-data-49financial"


def _is_mark(ln):
    return "GENERATED by lib/opal_naming.py" in ln


def rehearse(root):
    sys.path.insert(0, os.path.join(root, "lib"))
    import opal_naming as on
    tmp = tempfile.mkdtemp(prefix="r4flip_")
    outs = {}
    n_edit = 0
    for arm in ("base", "flip"):
        reg = os.path.join(tmp, arm + "_registry")
        shutil.copytree(os.path.join(root, "infra", "logic", "registry"), reg)
        if arm == "flip":
            sp = os.path.join(reg, "scopes.json")
            raw = open(sp, encoding="utf-8", newline="").read()
            d = json.loads(raw)
            # a TEXT edit of the one alias block keeps every other byte, so the only difference is the routed marker
            for s in d.get("scopes", []):
                if s.get("key") == SCOPE:
                    for a in s.get("aliases", []):
                        if a.get("spelling") == ALIAS and a.get("routed") is True:
                            n_edit += 1
            i = raw.index('"spelling": "%s"' % ALIAS)
            j = raw.index('"routed": true', i)
            raw = raw[:j] + '"routed": false' + raw[j + len('"routed": true'):]
            with open(sp, "w", encoding="utf-8", newline="") as fh:
                fh.write(raw)
        on.REGISTRY_DIR = reg
        on._CACHE.clear()
        if hasattr(on, "_VOCAB_CACHE"):
            on._VOCAB_CACHE.clear()
        out = os.path.join(tmp, arm + "_out")
        results = on.generate(out, None)
        outs[arm] = (out, results)
    return tmp, outs, n_edit


def flip(root):
    tmp, outs, n_edit = rehearse(root)
    res = []
    res.append(("F1 the scratch registry flips exactly the one routed alias of the 49financial scope", n_edit == 1))
    (out0, _), (out1, r1) = outs["base"], outs["flip"]
    wrote = [t for st, t, _ in r1 if st == "WROTE"]
    changed = {}
    for t in wrote:
        p0, p1 = os.path.join(out0, *t.split("/")), os.path.join(out1, *t.split("/"))
        if not (os.path.isfile(p0) and os.path.isfile(p1)):
            continue
        a = [ln for ln in open(p0, encoding="utf-8", errors="replace").read().splitlines() if not _is_mark(ln)]
        b = [ln for ln in open(p1, encoding="utf-8", errors="replace").read().splitlines() if not _is_mark(ln)]
        if a != b:
            changed[t] = [ln for ln in difflib.unified_diff(a, b, lineterm="", n=0)
                          if ln[:1] in "+-" and ln[:3] not in ("+++", "---")]
    print("  generated targets=%d; value changes under the flip (mark lines excluded)=%d" % (len(wrote), len(changed)))
    for t, diff in sorted(changed.items()):
        print("  CHANGES %s (%d lines)" % (t, len(diff)))
        for ln in diff[:6]:
            print("      " + ln[:150])
    names = set(changed)
    print("  not value-changing readers named by the CTO's list: %s" % sorted(set(READERS) - names))
    print("  value-changing targets the CTO's list does not name: %s" % sorted(names - set(READERS)))
    res.append(("F2 at least one generated target changes value under the flip", bool(names)))
    res.append(("F3 the value-changing set equals the enumerated expectation (5 targets: firm_registry.json, "
                "firm-config.mjs, directory_runner.py, holdings_snapshot.py, _asset_dim_rest_pin.py)",
                names == EXPECTED))
    only_bucket = all(all((OLD in ln or NEW in ln) for ln in diff) for diff in changed.values())
    res.append(("F4 in every value-changing target only the bucket value moves (each changed line names %s or %s)"
                % (OLD, NEW), only_bucket and bool(changed)))
    shutil.rmtree(tmp, ignore_errors=True)
    return res


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--arms", choices=("flip",), required=True)
    ap.add_argument("--root")
    a = ap.parse_args()
    root = _root(a.root)
    try:
        res = flip(root)
    except Exception as e:  # noqa: BLE001
        print("ABSENT or unreadable: rehearsal (%s: %s)" % (type(e).__name__, str(e)[:200]))
        res = [("the rehearsal ran", False)]
    for name, ok in res:
        print("%s %s" % ("PASS" if ok else "FAIL", name))
    n = sum(1 for _, ok in res if ok)
    print("ROUND 4 FLIP %s: %d of 4 arms" % (a.arms.upper(), n))
    sys.exit(0 if n == 4 else 1)


if __name__ == "__main__":
    main()
