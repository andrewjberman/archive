"""ADVI_FIRMBKTS round 4 check for cell FB-g-14 (the transitional IRPT live row; the CTO's round-3 ADDENDUM 6, row D1-S24),
issuer 2.0.0_SA_COO~B1.

--arms live [--root <tree>] [--base <ref>]  (5 arms)
  I1 the 49financial scope row carries product_live.irpt: bucket opal-data-bd, transitional true, a non-empty owner naming
     IRPT_BCKEND and a non-empty expiry.
  I2 `python lib/opal_naming.py validate` exits 0.
  I3 the targets that carry the IRPT bucket map (data/firm_registry.json, directory_runner.py, holdings_snapshot.py) are
     generated from that row: the renderers of firm_registry rows and firm_bucket_map read product_live, and only
     FIRM_CONFIG still reads `_routed_bucket` (read from the tree's lib/opal_naming.py, code lines only).
  I4 DORMANT: every generated target the builder lists whose mark covers scopes.json is in sync with the builder and changes
     no non-mark line against the base (targets under the nested portal repository are skipped and printed).
  I5 the flip rehearsal's value-changing set is exactly the router, guard and validator's firm-config.mjs.
Plain ASCII output; the last line carries the arm count. Never edit this file.
"""
import argparse
import difflib
import json
import os
import re
import shutil
import subprocess
import sys
import tempfile

FC = "infra/aws/lambda-edge/_shared/firm-config.mjs"


def _git(root, *a):
    return subprocess.run(["git", "-C", root] + list(a), capture_output=True, text=True, encoding="utf-8",
                          errors="replace")


def _root(arg):
    if arg:
        return arg
    return subprocess.run(["git", "rev-parse", "--show-toplevel"], capture_output=True, text=True).stdout.strip()


def _base(root, arg):
    if arg:
        return arg
    wl = _git(root, "worktree", "list", "--porcelain").stdout.split("\n")
    primary = next((ln.split()[1] for ln in wl if ln.startswith("HEAD ")), "")
    return _git(root, "merge-base", "HEAD", primary).stdout.strip()


def _nm(text):
    return [ln for ln in text.splitlines() if "GENERATED by lib/opal_naming.py" not in ln]


def _func(src, name):
    m = re.search(r"def %s\(.*?\n(?=def |\Z)" % re.escape(name), src, re.S)
    if not m:
        return ""
    body = re.sub(r'""".*?"""', "", m.group(0), flags=re.S)
    return "\n".join(ln for ln in body.splitlines() if not ln.strip().startswith("#"))


def live(root, base):
    res = []
    sp = os.path.join(root, "infra", "logic", "registry", "scopes.json")
    row = {}
    for s in json.load(open(sp, encoding="utf-8")).get("scopes", []):
        if s.get("key") == "49financial":
            row = ((s.get("product_live") or {}).get("irpt")) or {}
    ok1 = row.get("bucket") == "opal-data-bd" and row.get("transitional") is True \
        and "IRPT_BCKEND" in str(row.get("owner", "")) and bool(str(row.get("expiry", "")).strip())
    print("  product_live.irpt = %s" % (json.dumps(row)[:200] if row else None))
    res.append(("I1 the 49financial scope row carries the transitional IRPT live bucket with owner IRPT_BCKEND and expiry",
                ok1))

    r = subprocess.run([sys.executable, "lib/opal_naming.py", "validate"], cwd=root, capture_output=True, text=True,
                       timeout=100)
    print("  validate rc=%d" % r.returncode)
    res.append(("I2 lib/opal_naming.py validate exits 0", r.returncode == 0))

    src = open(os.path.join(root, "lib", "opal_naming.py"), encoding="utf-8").read()
    fr = _func(src, "_firm_registry_rows")
    fb = _func(src, "_blk_firm_bucket_map")
    fc = _func(src, "_blk_firm_config")
    ok3 = "product_live" in (fr + fb + src[src.find("def _irpt_bucket"):src.find("def _irpt_bucket") + 600]) \
        and "_routed_bucket" not in fr and "_routed_bucket" not in fb and "_routed_bucket" in fc
    print("  firm_registry rows read routed=%s; firm_bucket_map reads routed=%s; FIRM_CONFIG reads routed=%s"
          % ("_routed_bucket" in fr, "_routed_bucket" in fb, "_routed_bucket" in fc))
    res.append(("I3 the IRPT bucket map targets read the live row; only FIRM_CONFIG reads the routed bucket", ok3))

    code = ("import sys,json; sys.path.insert(0,'lib'); import opal_naming as n; n.generate(sys.argv[1], None); "
            "print(json.dumps([k for k,v in n.TARGET_REGISTRY_KEYS.items() if 'scopes' in v]))")
    with tempfile.TemporaryDirectory() as td:
        g = subprocess.run([sys.executable, "-c", code, td], cwd=root, capture_output=True, text=True, timeout=170)
        try:
            targets = json.loads(g.stdout.strip().splitlines()[-1])
        except Exception:  # noqa: BLE001
            targets = []
        stale, drift, skipped = [], [], []
        for t in targets:
            if _git(root, "ls-files", "--error-unmatch", t).returncode != 0:
                skipped.append(t)
                continue
            cur_p = os.path.join(root, *t.split("/"))
            gen_p = os.path.join(td, *t.split("/"))
            cur = open(cur_p, encoding="utf-8", errors="replace").read() if os.path.isfile(cur_p) else ""
            gen = open(gen_p, encoding="utf-8", errors="replace").read() if os.path.isfile(gen_p) else None
            if gen is None or cur != gen:
                stale.append(t)
            if _nm(_git(root, "show", "%s:%s" % (base, t)).stdout) != _nm(cur):
                drift.append(t)
    print("  targets covering scopes.json=%d (skipped %s); out of sync=%s; value-changed against the base=%s"
          % (len(targets), skipped, stale, drift))
    res.append(("I4 dormant: every target covering scopes.json is in sync and changes no non-mark line against the base",
                bool(targets) and not stale and not drift))

    # I5: the flip rehearsal (scratch registry copy, text edit of the routed alias), as r4_flip.py does
    sys.path.insert(0, os.path.join(root, "lib"))
    import opal_naming as on  # noqa: E402
    changed = set()
    tmp = tempfile.mkdtemp(prefix="r4irpt_")
    try:
        outs = {}
        for arm in ("base", "flip"):
            reg = os.path.join(tmp, arm + "_registry")
            shutil.copytree(os.path.join(root, "infra", "logic", "registry"), reg)
            if arm == "flip":
                p = os.path.join(reg, "scopes.json")
                raw = open(p, encoding="utf-8", newline="").read()
                i = raw.index('"spelling": "opal-data-bd"')
                j = raw.index('"routed": true', i)
                raw = raw[:j] + '"routed": false' + raw[j + len('"routed": true'):]
                open(p, "w", encoding="utf-8", newline="").write(raw)
            on.REGISTRY_DIR = reg
            on._CACHE.clear()
            if hasattr(on, "_VOCAB_CACHE"):
                on._VOCAB_CACHE.clear()
            out = os.path.join(tmp, arm + "_out")
            results = on.generate(out, None)
            outs[arm] = (out, results)
        (o0, _), (o1, r1) = outs["base"], outs["flip"]
        for st, t, _ in r1:
            if st != "WROTE":
                continue
            p0, p1 = os.path.join(o0, *t.split("/")), os.path.join(o1, *t.split("/"))
            if os.path.isfile(p0) and os.path.isfile(p1):
                a = _nm(open(p0, encoding="utf-8", errors="replace").read())
                b = _nm(open(p1, encoding="utf-8", errors="replace").read())
                if list(difflib.unified_diff(a, b, lineterm="", n=0)):
                    changed.add(t)
    finally:
        shutil.rmtree(tmp, ignore_errors=True)
    print("  value-changing set under the flip: %s" % sorted(changed))
    res.append(("I5 the flip's value-changing set is exactly firm-config.mjs", changed == {FC}))
    return res


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--arms", choices=("live",), required=True)
    ap.add_argument("--root")
    ap.add_argument("--base")
    a = ap.parse_args()
    root = _root(a.root)
    try:
        res = live(root, _base(root, a.base))
    except Exception as e:  # noqa: BLE001
        print("ABSENT or unreadable: (%s: %s)" % (type(e).__name__, str(e)[:160]))
        res = [("the registry and builder readable at the tree and the base", False)]
    for name, ok in res:
        print("%s %s" % ("PASS" if ok else "FAIL", name))
    n = sum(1 for _, ok in res if ok)
    print("ROUND 4 IRPT LIVE: %d of 5 arms" % n)
    sys.exit(0 if n == 5 else 1)


if __name__ == "__main__":
    main()
