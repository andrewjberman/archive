"""ADVI_FIRMBKTS round 4 check for cell FB-g-16 (the IRPT ownership-map read follows the routed bucket; the CTO's round-3
ADDENDUM 7, row D1-S25), issuer 2.0.0_SA_COO~B1.

--arms read [--root <tree>] [--base <ref>]  (5 arms; the loader is imported from the tree and its S3 read is stubbed)
  W1 loaders.py carries a generated OWNERSHIP_READ block with exactly one entry per firm that owns a REGISTERED legacy
     ownership-map address; each entry's `bucket` is the scope's routed bucket and its `legacy` and `canonical` keys are the
     registered template and the producers' seam's canonical destination for it (read from the tree, never typed here).
  W2 DORMANT: with the directory bucket map pointing at a DIFFERENT live bucket and no canonical list, load_ownership reads
     (routed bucket, legacy key) for a registered owner, while load_directory still reads the map's bucket.
  W3 ENGAGED: with the routed bucket named in IRPT_PLATINUM_CANONICAL_BUCKETS the key is the canonical key; with another
     bucket named it stays legacy.
  W4 a tenant with no registered owner reads exactly as before (bucket_for(tenant) and the template key).
  W5 loaders.py is the builder's output, validate exits 0, and no other generated target covering scopes.json changes a
     non-mark line against the base.
Plain ASCII output; the last line carries the arm count. Never edit this file.
"""
import argparse
import importlib.util
import json
import os
import subprocess
import sys
import tempfile

LOADERS = "infra/aws/lambda/investor-reporting/_authz/loaders.py"


def _git(root, *a):
    return subprocess.run(["git", "-C", root] + list(a), capture_output=True, text=True, encoding="utf-8",
                          errors="replace")


def _root(arg):
    if arg:
        return arg
    return subprocess.run(["git", "rev-parse", "--show-toplevel"], capture_output=True, text=True).stdout.strip()


def _base(root, arg):
    if arg:
        return arg
    wl = _git(root, "worktree", "list", "--porcelain").stdout.split("\n")
    primary = next((ln.split()[1] for ln in wl if ln.startswith("HEAD ")), "")
    return _git(root, "merge-base", "HEAD", primary).stdout.strip()


def _nm(text):
    return [ln for ln in text.splitlines() if "GENERATED by lib/opal_naming.py" not in ln]


def _load(root, env):
    for k in ("IRPT_DIRECTORY_BUCKET_MAP", "IRPT_PLATINUM_CANONICAL_BUCKETS", "IRPT_OWNERSHIP_KEY", "IRPT_DIRECTORY_PREFIX"):
        os.environ.pop(k, None)
    os.environ.update(env)
    spec = importlib.util.spec_from_file_location("r4_loaders_under_test", os.path.join(root, *LOADERS.split("/")))
    mod = importlib.util.module_from_spec(spec)
    spec.loader.exec_module(mod)
    return mod


def read(root, base):
    res = []
    sys.path.insert(0, os.path.join(root, "lib"))
    sys.path.insert(0, os.path.join(root, "data", "black_diamond", "scripts", "gold"))
    import opal_naming  # noqa: E402
    from lib import platinum_dest as pd  # noqa: E402
    reg = opal_naming._registry()
    rows = [r for r in reg["legacy_addresses"]["legacy_addresses"]
            if str(r.get("key", "")).endswith("-ownership-map") and r.get("shape") == "object"]
    classes = reg["platinum_destinations"]["platinum_destinations"]
    expect = {}
    for r in rows:
        for c in classes:
            if r["template"].startswith(c["legacy_prefix"]):
                srow = opal_naming.lookup(c["scope"], reg)
                expect[c["scope"]] = {"bucket": opal_naming._routed_bucket(srow), "legacy": r["template"],
                                      "canonical": pd.destination(r["template"], "canonical")[1]}
    owner = next(iter(sorted(expect)), None)

    got = {}
    ok1 = False
    mod = None
    try:
        mod = _load(root, {})
        got = getattr(mod, "OWNERSHIP_READ", None) or {}
        ok1 = bool(expect) and {k: dict(v) for k, v in got.items()} == expect
    except Exception as e:  # noqa: BLE001
        print("  loaders.py import failed: %s: %s" % (type(e).__name__, str(e)[:120]))
    print("  OWNERSHIP_READ entries=%s expected owners=%s" % (sorted(got), sorted(expect)))
    res.append(("W1 loaders.py carries a generated OWNERSHIP_READ for exactly the registered owners (routed bucket, "
                "registered legacy key, the seam's canonical key)", ok1))
    if not ok1 or owner is None:
        return res + [("W2 dormant read", False), ("W3 engaged read", False), ("W4 unregistered tenant", False),
                      ("W5 in sync and dormant", False)]

    def captured(env, tenant, which):
        m = _load(root, env)
        seen = []

        def fake_get_json(bucket, key, s3=None):
            seen.append((bucket, key))
            return {"schema_version": 1, "advisors": {}, "key": "x"}
        m._get_json = fake_get_json
        try:
            if which == "ownership":
                m.load_ownership(tenant, s3=object())
            else:
                m.load_directory(tenant, s3=object())
        except Exception:  # noqa: BLE001
            pass
        return seen[:1]

    live = "x-live-bucket-for-the-check"
    env = {"IRPT_DIRECTORY_BUCKET_MAP": json.dumps({owner: live, "no-registered-owner": live})}
    own = captured(env, owner, "ownership")
    dr = captured(env, owner, "directory")
    ok2 = own == [(expect[owner]["bucket"], expect[owner]["legacy"])] and dr and dr[0][0] == live
    print("  dormant: ownership read %s; directory read %s" % (own, dr))
    res.append(("W2 dormant: the ownership read is (routed bucket, legacy key) and the directory read stays on the map's "
                "bucket", bool(ok2)))

    named = captured(dict(env, IRPT_PLATINUM_CANONICAL_BUCKETS=expect[owner]["bucket"]), owner, "ownership")
    other = captured(dict(env, IRPT_PLATINUM_CANONICAL_BUCKETS="x-some-other-bucket"), owner, "ownership")
    ok3 = named == [(expect[owner]["bucket"], expect[owner]["canonical"])] and \
        other == [(expect[owner]["bucket"], expect[owner]["legacy"])]
    print("  engaged: named %s; other %s" % (named, other))
    res.append(("W3 engaged: the named routed bucket reads the canonical key, another stays legacy", ok3))

    m = _load(root, env)
    tmpl = m.OWNERSHIP_KEY_TEMPLATE.format(firm="no-registered-owner")
    un = captured(env, "no-registered-owner", "ownership")
    ok4 = un == [(live, tmpl)]
    print("  unregistered tenant read %s" % (un,))
    res.append(("W4 a tenant with no registered owner reads bucket_for(tenant) and the template key, as before", ok4))

    code = ("import sys,json; sys.path.insert(0,'lib'); import opal_naming as n; n.generate(sys.argv[1], None); "
            "print(json.dumps([k for k,v in n.TARGET_REGISTRY_KEYS.items() if 'scopes' in v]))")
    with tempfile.TemporaryDirectory() as td:
        g = subprocess.run([sys.executable, "-c", code, td], cwd=root, capture_output=True, text=True, timeout=170)
        try:
            targets = json.loads(g.stdout.strip().splitlines()[-1])
        except Exception:  # noqa: BLE001
            targets = []
        stale, drift = [], []
        for t in targets:
            if _git(root, "ls-files", "--error-unmatch", t).returncode != 0:
                continue
            cur_p, gen_p = os.path.join(root, *t.split("/")), os.path.join(td, *t.split("/"))
            cur = open(cur_p, encoding="utf-8", errors="replace").read()
            gen = open(gen_p, encoding="utf-8", errors="replace").read() if os.path.isfile(gen_p) else None
            if gen is None or cur != gen:
                stale.append(t)
            if t != LOADERS and _nm(_git(root, "show", "%s:%s" % (base, t)).stdout) != _nm(cur):
                drift.append(t)
    v = subprocess.run([sys.executable, "lib/opal_naming.py", "validate"], cwd=root, capture_output=True, text=True,
                       timeout=100)
    print("  out of sync=%s; other targets value-changed=%s; validate rc=%d" % (stale, drift, v.returncode))
    res.append(("W5 loaders.py is the builder's output, validate exits 0 and no other generated target changes a "
                "non-mark line", bool(targets) and not stale and not drift and v.returncode == 0))
    return res


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--arms", choices=("read",), required=True)
    ap.add_argument("--root")
    ap.add_argument("--base")
    a = ap.parse_args()
    root = _root(a.root)
    try:
        res = read(root, _base(root, a.base))
    except Exception as e:  # noqa: BLE001
        print("ABSENT or unreadable: %s (%s: %s)" % (LOADERS, type(e).__name__, str(e)[:160]))
        res = [("the IRPT loaders readable at the tree and the base", False)]
    for name, ok in res:
        print("%s %s" % ("PASS" if ok else "FAIL", name))
    n = sum(1 for _, ok in res if ok)
    print("ROUND 4 IRPT OWNERSHIP READ: %d of 5 arms" % n)
    sys.exit(0 if n == 5 else 1)


if __name__ == "__main__":
    main()
