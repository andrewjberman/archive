"""ADVI_FIRMBKTS round 4 check for cell FB-g-11 (the transitional bronze-live registry row, the CTO's ADDENDUM 3 to
ROUND_ANALYSIS.round3.md), issuer 2.0.0_SA_COO~B1.

--arms live [--root <tree>] [--base <ref>]  (5 arms)
  D1 the 49financial scope row carries tier_live.bronze: bucket opal-data-bd, transitional true, a non-empty owner and a
     non-empty expiry.
  D2 `python lib/opal_naming.py validate` exits 0 in the tree.
  D3 every generated target whose registry mark covers scopes.json is IN SYNC: the committed file equals what the tree's
     builder generates now (marks included).
  D4 DORMANT: for those same targets, every non-mark line of the committed file equals the base's (the base is the
     merge-base of HEAD and the primary checkout's HEAD): nothing changes value now.
  D5 the pin's renderer no longer reads the routed alias: `_blk_asset_dim_rest_pin` names tier_live and not `routed`.
A target under the nested portal repository is skipped and printed (its registry mark is the portal's own commit).
Plain ASCII output; the last line carries the arm count. Never edit this file.
"""
import argparse
import json
import os
import re
import subprocess
import sys
import tempfile


def _git(root, *a):
    return subprocess.run(["git", "-C", root] + list(a), capture_output=True, text=True, encoding="utf-8", errors="replace")


def _root(arg):
    if arg:
        return arg
    return subprocess.run(["git", "rev-parse", "--show-toplevel"], capture_output=True, text=True).stdout.strip()


def _base(root, arg):
    if arg:
        return arg
    wl = _git(root, "worktree", "list", "--porcelain").stdout.split("\n")
    primary = next((ln.split()[1] for ln in wl if ln.startswith("HEAD ")), "")
    return _git(root, "merge-base", "HEAD", primary).stdout.strip()


def _nm(text):
    return [ln for ln in text.splitlines() if "GENERATED by lib/opal_naming.py" not in ln]


def live(root, base):
    res = []
    sp = os.path.join(root, "infra", "logic", "registry", "scopes.json")
    row = None
    for s in json.load(open(sp, encoding="utf-8")).get("scopes", []):
        if s.get("key") == "49financial":
            row = ((s.get("tier_live") or {}).get("bronze")) or {}
    ok1 = bool(row) and row.get("bucket") == "opal-data-bd" and row.get("transitional") is True \
        and bool(str(row.get("owner", "")).strip()) and bool(str(row.get("expiry", "")).strip())
    print("  tier_live.bronze = %s" % (json.dumps(row)[:200] if row else None))
    res.append(("D1 the 49financial scope row carries the transitional bronze live bucket with owner and expiry", ok1))

    r = subprocess.run([sys.executable, "lib/opal_naming.py", "validate"], cwd=root, capture_output=True, text=True,
                       timeout=100)
    print("  validate rc=%d: %s" % (r.returncode, (r.stdout.strip().splitlines() or [""])[-1][:140]))
    res.append(("D2 lib/opal_naming.py validate exits 0", r.returncode == 0))

    code = ("import sys,json; sys.path.insert(0,'lib'); import opal_naming as n; "
            "out=sys.argv[1]; n.generate(out, None); "
            "print(json.dumps([k for k,v in n.TARGET_REGISTRY_KEYS.items() if 'scopes' in v]))")
    with tempfile.TemporaryDirectory() as td:
        g = subprocess.run([sys.executable, "-c", code, td], cwd=root, capture_output=True, text=True, timeout=160)
        try:
            targets = json.loads(g.stdout.strip().splitlines()[-1])
        except Exception:  # noqa: BLE001
            targets = []
        stale, drift, skipped = [], [], []
        for t in targets:
            if _git(root, "ls-files", "--error-unmatch", t).returncode != 0:
                skipped.append(t)  # a path of the nested portal repository: not this repository's to commit
                continue
            cur_p = os.path.join(root, *t.split("/"))
            gen_p = os.path.join(td, *t.split("/"))
            cur = open(cur_p, encoding="utf-8", errors="replace").read() if os.path.isfile(cur_p) else ""
            gen = open(gen_p, encoding="utf-8", errors="replace").read() if os.path.isfile(gen_p) else None
            if gen is None or cur != gen:
                stale.append(t)
            old = _git(root, "show", "%s:%s" % (base, t)).stdout
            if _nm(old) != _nm(cur):
                drift.append(t)
    print("  targets covering scopes.json=%d (not tracked in this repository, skipped: %s); out of sync=%s; "
          "value-changed against the base=%s" % (len(targets), skipped, stale, drift))
    res.append(("D3 every target covering scopes.json is in sync with the builder", bool(targets) and not stale))
    res.append(("D4 dormant: no such target changes a non-mark line against the base", bool(targets) and not drift))

    src = open(os.path.join(root, "lib", "opal_naming.py"), encoding="utf-8").read()
    m = re.search(r"def _blk_asset_dim_rest_pin\(.*?\n(?=def )", src, re.S)
    body = m.group(0) if m else ""
    code_lines = "\n".join(ln for ln in body.splitlines() if not ln.strip().startswith("#"))
    # the docstring may say 'routed'; only code lines are read
    in_doc = re.sub(r'""".*?"""', "", code_lines, flags=re.S)
    ok5 = bool(body) and "tier_live" in in_doc and "routed" not in in_doc
    print("  pin renderer reads tier_live=%s, mentions routed in code=%s" % ("tier_live" in in_doc, "routed" in in_doc))
    res.append(("D5 the pin's renderer reads tier_live and not the routed alias", ok5))
    return res


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--arms", choices=("live",), required=True)
    ap.add_argument("--root")
    ap.add_argument("--base")
    a = ap.parse_args()
    root = _root(a.root)
    try:
        res = live(root, _base(root, a.base))
    except Exception as e:  # noqa: BLE001
        print("ABSENT or unreadable: (%s: %s)" % (type(e).__name__, str(e)[:160]))
        res = [("the registry and builder readable at the tree and the base", False)]
    for name, ok in res:
        print("%s %s" % ("PASS" if ok else "FAIL", name))
    n = sum(1 for _, ok in res if ok)
    print("ROUND 4 BRONZE LIVE: %d of 5 arms" % n)
    sys.exit(0 if n == 5 else 1)


if __name__ == "__main__":
    main()
