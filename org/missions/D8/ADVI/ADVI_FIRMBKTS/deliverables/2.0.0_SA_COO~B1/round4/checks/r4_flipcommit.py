"""ADVI_FIRMBKTS round 4: the act-4 FLIP COMMIT, as a tool (rehearsed in a scratch worktree, run for real at the act),
issuer 2.0.0_SA_COO~B1.

It applies act 4's ONE registry value in a checkout and regenerates every generated target IN PLACE, then reads what changed:
  1. the 49financial scope's alias `opal-data-bd` loses its routed marker (`"routed": true` -> `"routed": false`): a TEXT edit
     of that one alias block, so the file differs by that one line;
  2. `lib/opal_naming.py generate --out <root>` regenerates every target;
  3. `git status` is read: the registry file, the value-changing targets and the mark-line-only targets are listed; the
     value-changing set must equal the pair's two targets (firm-config.mjs, loaders.py); `validate` must exit 0.

  python r4_flipcommit.py --root <checkout> [--apply] [--base <ref>]
Without --apply it only READS (dry: it reports what the edit would be and exits 0 or 1 on the pre-edit state).
With --apply it edits and regenerates in <root> (a scratch worktree or the act's branch) and prints the result; it never
commits and never pushes. Last line: ROUND 4 FLIP COMMIT: <n> of 4 arms.
Plain ASCII.
"""
import argparse
import difflib
import json
import os
import subprocess
import sys

SCOPE = "49financial"
ALIAS = "opal-data-bd"
EXPECTED = {
    "infra/aws/lambda-edge/_shared/firm-config.mjs",
    "infra/aws/lambda/investor-reporting/_authz/loaders.py",
}
REG = "infra/logic/registry/scopes.json"


def _git(root, *a):
    return subprocess.run(["git", "-C", root] + list(a), capture_output=True, text=True, encoding="utf-8",
                          errors="replace")


def _is_mark(ln):
    return "GENERATED by lib/opal_naming.py" in ln


def verify(root, base):
    """Read a COMMITTED flip: the registry differs from <base> by exactly the one routed line; the value-changing targets are
    exactly the pair's two; every other changed file differs by its mark line only; `validate` exits 0 and every generated
    target is in sync (generate to a scratch dir equals the tree)."""
    res = []
    names = _git(root, "diff", "--name-only", base, "HEAD").stdout.split()
    reg = _git(root, "diff", "-U0", base, "HEAD", "--", REG).stdout
    changed_lines = [ln for ln in reg.splitlines() if ln[:1] in "+-" and ln[:3] not in ("+++", "---")]
    ok1 = REG in names and len(changed_lines) == 2 and '"routed": true' in changed_lines[0]         and '"routed": false' in changed_lines[1]
    print("  V1 registry diff lines=%s" % [ln.strip()[:40] for ln in changed_lines])
    res.append(("V1 the registry differs by exactly the one routed line (true to false)", ok1))
    value, mark = [], []
    for p in names:
        if p == REG:
            continue
        old = _git(root, "show", "%s:%s" % (base, p)).stdout.splitlines()
        new = _git(root, "show", "HEAD:%s" % p).stdout.splitlines()
        (value if [x for x in old if not _is_mark(x)] != [x for x in new if not _is_mark(x)] else mark).append(p)
    print("  V2 changed files=%d: value-changing %s; mark-line only %d" % (len(names), sorted(value), len(mark)))
    res.append(("V2 the value-changing targets are exactly the pair's two; the others differ by their mark line only",
                set(value) == EXPECTED))
    v = subprocess.run([sys.executable, "lib/opal_naming.py", "validate"], cwd=root, capture_output=True, text=True,
                       timeout=120)
    res.append(("V3 `validate` exits 0", v.returncode == 0))
    import tempfile
    with tempfile.TemporaryDirectory() as td:
        g = subprocess.run([sys.executable, "lib/opal_naming.py", "generate", "--out", td], cwd=root, capture_output=True,
                           text=True, timeout=300)
        drift = []
        for p in names:
            tp = os.path.join(td, *p.split("/"))
            if p == REG or not os.path.isfile(tp):
                continue
            if open(tp, encoding="utf-8", errors="replace").read() != _git(root, "show", "HEAD:%s" % p).stdout:
                drift.append(p)
    print("  V4 generate rc=%d; changed targets not equal to the builder's output: %s" % (g.returncode, drift))
    res.append(("V4 every changed generated target equals the builder's output at the committed registry",
                g.returncode == 0 and not drift))
    for n, ok in res:
        print("%s %s" % ("PASS" if ok else "FAIL", n))
    k = sum(1 for _, ok in res if ok)
    print("ROUND 4 FLIP COMMIT: %d of 4 arms" % k)
    return 0 if k == 4 else 1


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--root", required=True)
    ap.add_argument("--apply", action="store_true")
    ap.add_argument("--verify", action="store_true",
                    help="read the COMMITTED flip: git diff <base> HEAD in --root (no edit, no regeneration)")
    ap.add_argument("--base", default="HEAD")
    a = ap.parse_args()
    root = a.root
    res = []
    if a.verify:
        return verify(root, a.base)
    sp = os.path.join(root, *REG.split("/"))
    raw = open(sp, encoding="utf-8", newline="").read()
    d = json.loads(raw)
    live = [x for s in d.get("scopes", []) if s.get("key") == SCOPE for x in s.get("aliases", [])
            if x.get("spelling") == ALIAS and x.get("routed") is True]
    res.append(("P1 the alias carries the routed marker before the edit (exactly one)", len(live) == 1))
    if a.apply and len(live) == 1:
        i = raw.index('"spelling": "%s"' % ALIAS)
        j = raw.index('"routed": true', i)
        raw = raw[:j] + '"routed": false' + raw[j + len('"routed": true'):]
        with open(sp, "w", encoding="utf-8", newline="") as fh:
            fh.write(raw)
        r = subprocess.run([sys.executable, "lib/opal_naming.py", "generate", "--out", root], cwd=root,
                           capture_output=True, text=True, timeout=300)
        print("  generate rc=%d" % r.returncode)
        res.append(("P2 the builder regenerates every target (rc 0)", r.returncode == 0))
        st = _git(root, "status", "--porcelain").stdout.splitlines()
        paths = sorted(ln[3:].strip() for ln in st if ln[:2].strip() in ("M", "MM", "AM"))
        value, mark = [], []
        for p in paths:
            if p == REG:
                continue
            old = _git(root, "show", "%s:%s" % (a.base, p)).stdout.splitlines()
            try:
                new = open(os.path.join(root, *p.split("/")), encoding="utf-8", errors="replace").read().splitlines()
            except OSError:
                continue
            o = [ln for ln in old if not _is_mark(ln)]
            n = [ln for ln in new if not _is_mark(ln)]
            (value if o != n else mark).append(p)
        print("  changed files=%d: registry 1, value-changing %d, mark-line only %d" % (len(paths), len(value), len(mark)))
        for p in value:
            diff = [ln for ln in difflib.unified_diff(
                [x for x in _git(root, "show", "%s:%s" % (a.base, p)).stdout.splitlines() if not _is_mark(x)],
                [x for x in open(os.path.join(root, *p.split("/")), encoding="utf-8", errors="replace")
                 .read().splitlines() if not _is_mark(x)], lineterm="", n=0) if ln[:1] in "+-" and ln[:3] not in ("+++", "---")]
            print("  VALUE %s (%d lines)" % (p, len(diff)))
            for ln in diff[:6]:
                print("      " + ln[:150])
        res.append(("P3 the value-changing set is exactly the pair's two targets", set(value) == EXPECTED))
        v = subprocess.run([sys.executable, "lib/opal_naming.py", "validate"], cwd=root, capture_output=True, text=True,
                           timeout=120)
        res.append(("P4 `validate` exits 0 after the regeneration", v.returncode == 0))
    else:
        res.append(("P2 (not applied: dry read)", True))
        res.append(("P3 (not applied: dry read)", True))
        res.append(("P4 (not applied: dry read)", True))
    for n, ok in res:
        print("%s %s" % ("PASS" if ok else "FAIL", n))
    k = sum(1 for _, ok in res if ok)
    print("ROUND 4 FLIP COMMIT: %d of 4 arms" % k)
    return 0 if k == 4 else 1


if __name__ == "__main__":
    sys.exit(main())
