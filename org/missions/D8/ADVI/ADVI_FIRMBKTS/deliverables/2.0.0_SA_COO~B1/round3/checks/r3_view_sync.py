"""ADVI_FIRMBKTS round 3 check for cell FB-f-9 phase A (the CTO's ADDENDUM 3): the generated platinum-destination view is
the builder's own output.

Runs `python lib/opal_naming.py generate --out <tmp> --target <view>` from the tree named by --root and compares the
bytes it writes with the committed view. Prints `VIEW IN SYNC: <path> (<n> bytes)` and exits 0 only when the file is
present, was generated, carries the standard GENERATED mark, and is byte-identical. Any other state prints
`VIEW ABSENT, STALE OR HAND-KEPT: <why>` and exits 1. Never edit this file. Plain ASCII.
"""
import argparse
import os
import subprocess
import sys
import tempfile

VIEW = "data/black_diamond/scripts/gold/lib/platinum_dest_view.json"
MARK = "GENERATED by lib/opal_naming.py from"


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--root")
    a = ap.parse_args()
    root = a.root or subprocess.run(["git", "rev-parse", "--show-toplevel"], capture_output=True, text=True).stdout.strip()
    path = os.path.join(root, VIEW)
    if not os.path.isfile(path):
        print("VIEW ABSENT, STALE OR HAND-KEPT: %s is absent" % VIEW)
        return 1
    with tempfile.TemporaryDirectory() as td:
        r = subprocess.run([sys.executable, os.path.join(root, "lib", "opal_naming.py"), "generate", "--out", td,
                            "--target", VIEW], capture_output=True, text=True, cwd=root, timeout=100)
        gen = os.path.join(td, VIEW)
        if r.returncode != 0 or not os.path.isfile(gen):
            print("VIEW ABSENT, STALE OR HAND-KEPT: generate rc=%d wrote no %s: %s"
                  % (r.returncode, VIEW, (r.stdout + r.stderr).strip()[:200]))
            return 1
        want = open(gen, "rb").read()
    have = open(path, "rb").read()
    if MARK.encode("ascii") not in have:
        print("VIEW ABSENT, STALE OR HAND-KEPT: the committed file carries no GENERATED mark")
        return 1
    if have != want:
        print("VIEW ABSENT, STALE OR HAND-KEPT: the committed bytes differ from the builder's output (%d vs %d bytes)"
              % (len(have), len(want)))
        return 1
    print("VIEW IN SYNC: %s (%d bytes)" % (VIEW, len(have)))
    return 0


if __name__ == "__main__":
    sys.exit(main())
