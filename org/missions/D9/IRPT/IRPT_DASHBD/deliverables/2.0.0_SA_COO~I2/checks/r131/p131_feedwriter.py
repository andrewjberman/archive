class Fail(Exception):
    pass


def need(cond, msg):
    if not cond:
        raise Fail(msg)


def _load(name, path):
    spec = importlib.util.spec_from_file_location(name, str(path))
    mod = importlib.util.module_from_spec(spec)
    spec.loader.exec_module(mod)
    return mod


P129 = _load("p129_realrow", HERE.parent / "r129" / "p129_realrow.py")


def feed_partitions(root):
    """{ 'date=<day>': DataFrame } written by the feed's own run() over the feed's own fake S3 and canned Scope replies."""
    import pandas as pd
    root = Path(root)
    sys.path.insert(0, str(root / "lib"))
    sys.path.insert(0, str(root / FEED_DIR))
    import pull_inflection_scope_account_returns as M
    import test_scope_feed_daily_factor as T
    s3 = T._fixture_s3()
    code, _t, _p = T._run(s3, T._ended_responses(), from_date=DAYS[0])
    need(code == 0, "the feed's own run exited %r" % code)
    out = {}
    for day in DAYS:
        bucket, key = M._split(M.feed_addresses(day)[1])
        need((bucket, key) in s3.objects, "the feed wrote no silver for %s" % day)
        out["date=" + day] = pd.read_parquet(io.BytesIO(s3.objects[(bucket, key)]))
    return out


def weekdays(lo, hi):
    return P129.weekdays(lo, hi)


def load_wrapper(root):
    adapters = Path(root) / "data/assets/scripts/gold/irpt_reporting/adapters"
    sys.path.insert(0, str(adapters))
    sys.path.insert(0, str(root))
    return _load("scope_feed_run_under_test", adapters / "inflection_scope_feed_run.py")


def grade_wrapper(root):
    import pandas as pd
    import pyarrow.parquet as pq
    wrapper = load_wrapper(root)
    cmod = _load("contract_042_tests", Path(root) / CONTRACT_TEST_REL)
    silver = feed_partitions(root)
    need(sorted(silver) == ["date=" + d for d in DAYS], "partitions: %s" % sorted(silver))
    need(all(set(f["pull_date"]) == {"2026-10-14"} for f in silver.values()), "the feed's pull_date was expected to be the pull day on every row")
    dim = pd.DataFrame({"account_id": [str(a) for a in ACCOUNTS]})
    with tempfile.TemporaryDirectory() as td:
        out = Path(td) / "out"
        rec = wrapper.run(silver, dim, weekdays(DAYS[0], DAYS[-1]), FIRM, 0, str(out))
        rows = []
        for p in sorted(out.glob("date=*")):
            rows.extend(pq.read_table(str(p / "data.parquet")).to_pylist())
    n = len(ACCOUNTS) * len(DAYS)
    need(len(rows) == n, "rows: %d, want %d (every account x trading day once)" % (len(rows), n))
    need(len({(r["source_account_id"], r["business_date"]) for r in rows}) == n, "an (account, day) pair repeats or is missing")
    need(rec["rows_present"] + rec["rows_absent"] == n and rec["trading_days_unaccounted"] == 0, "run record counts: %r" % {k: rec[k] for k in ("rows_present", "rows_absent", "trading_days_unaccounted")})
    need(rec["accounts_in_feed"] == len(ACCOUNTS) and rec["calendar_days_read"] == len(DAYS) and rec["calendar_days_incomplete"] == 0, "run record days / accounts")
    need(sum(rec["absent_by_reason"].values()) == rec["rows_absent"] and set(rec["absent_by_reason"]) <= REASONS, "absent_by_reason: %r" % rec["absent_by_reason"])
    need(sum(rec["market_value_eod_claim_counts"].values()) == rec["rows_present"], "claim counts must sum to rows_present")
    for r in rows:
        probs = cmod.row_problems(cmod.CONTRACT, r)
        need(not probs, "contract validator on a %s row: %s" % (r["row_status"], probs))
    need(rec["contract_version"] == cmod.CONTRACT["contract_version"], "contract_version")
    return silver


def grade_run_real(root):
    script = _load("run_scope_feed_real_under_test", Path(root) / P129.SCRIPT_REL)  # first: it binds `lib` to the repository's
    silver = feed_partitions(root)
    with tempfile.TemporaryDirectory() as td:
        rec = script.run_real(P129.FakeReader({"scope_account_returns": silver}), str(Path(td) / "out"), [str(a) for a in ACCOUNTS], weekdays, FIRM, 0, 400)
    need(rec.get("status") == "RAN" and set(rec) == P129.TOP_RAN, "run_real record: status %r, key diff %s" % (rec.get("status"), sorted(set(rec) ^ P129.TOP_RAN)))
    need(rec["partitions_read"] == len(DAYS) and rec["s3_reads"] == 1 + len(DAYS), "reads: %r" % (rec["s3_reads"],))
    need(rec["trading_days_unaccounted"] == 0 and rec["rows_present"] + rec["rows_absent"] == len(ACCOUNTS) * len(DAYS), "counts")
    text = json.dumps(rec)
    need(re.search(r"\d{8,}", text) is None and re.search(r"\d{4}-\d{2}-\d{2}", text) is None, "an 8-digit run or a date in the record")


def grade_tests(root):
    tf = Path(root) / TEST_REL
    need(tf.is_file(), "no test file at %s" % TEST_REL)
    src = tf.read_bytes().decode("ascii")
    need("pull_inflection_scope_account_returns" in src, "the test file never imports the feed module")
    alias = re.search(r"import pull_inflection_scope_account_returns as (\w+)", src)
    runs_feed = (alias is not None and ("%s.run(" % alias.group(1)) in src) or re.search(r"\w+\._run\(", src) is not None
    need(runs_feed, "the test file never calls the feed's run() (directly, or through the feed's own harness _run)")
    need("M.feed_addresses" in src or "feed_addresses(" in src, "the test file never reads the feed's own silver addresses")
    for bad in ("pd.DataFrame([", "pandas.DataFrame([", "DataFrame({\"pull_date\"", "DataFrame({'pull_date'"):
        need(bad not in src, "the test file hand-builds a frame (%s); a feed frame must come from the feed's run()" % bad)
    need(re.search(r"^def test_\w*mutant\w*\(", src, re.M) is not None, "no test named test_*mutant*")
    r = subprocess.run([sys.executable, "-I", "-m", "pytest", "-q", "-p", "no:cacheprovider", str(tf)], cwd=str(root), capture_output=True, text=True, timeout=100)
    tail = (r.stdout or "").strip().splitlines()[-1:] or [""]
    need(r.returncode == 0, "pytest rc %s: %s" % (r.returncode, tail[0]))
    m = re.search(r"(\d+) passed", r.stdout or "")
    need(m is not None and int(m.group(1)) >= 6, "fewer than 6 passed tests: %s" % tail[0])


def selftest(root):
    need(weekdays(DAYS[0], DAYS[-1]) == DAYS, "weekdays drifted")
    need(len(ACCOUNTS) * len(DAYS) == 15, "world drifted")
    print("selftest PASS")


def main(argv):
    if len(argv) >= 2 and argv[1] == "--selftest":
        selftest(Path(argv[2]) if len(argv) > 2 else Path("."))
        return 0
    root, cid = Path(argv[1]).resolve(), argv[2]
    try:
        if cid == "DBI131-1-AC1":
            grade_wrapper(root)
        elif cid == "DBI131-1-AC2":
            grade_run_real(root)
        elif cid == "DBI131-1-AC3":
            grade_tests(root)
        else:
            raise Fail("unknown criterion %s" % cid)
    except Fail as exc:
        print("REASON: %s" % exc)
        print("%s FAIL" % cid)
        return 1
    except Exception as exc:  # a crash is a FAIL with its type named, never a pass
        print("REASON: %s: %s" % (type(exc).__name__, str(exc)[:300]))
        print("%s FAIL" % cid)
        return 1
    print("%s PASS" % cid)
    return 0


if __name__ == "__main__":
    sys.exit(main(sys.argv))
