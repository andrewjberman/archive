def pair(route_key, function, operation, schema, event, expect, denied_cases, stubs=None, notes=None, protected=None,
         control=None, driver="entry"):
    base = {"fixture_schema": "irpt-gated-route-fixture/1", "route": route_key, "function": function, "operation": operation,
            "request_contract": [ROUTES_JSON + "#" + route_key] + ([CONTRACT_DIR + schema] if schema else [])}
    allowed = dict(base, principal_class=("ALLOWED: FIRM_ADVISOR ADV-A-0001 of 49financial, grant A1+A2+A3" if driver == "entry" else
                                          "ALLOWED: the OWNER of the retained request / the admitted partner advisor of the offline world"),
                   event=event, expect=expect, driver=driver)
    if stubs:
        allowed["stubs"] = stubs
    if notes:
        allowed["notes"] = notes
    if protected:
        allowed["protected_values"] = protected
    if control:
        allowed["control_principal"] = control
    denied = dict(base, principal_class="DENIED: see cases (same request shape, one change each)", cases=denied_cases)
    s = slug(route_key)
    for suffix, doc in ((".allowed.json", allowed), (".denied.json", denied)):
        with open(os.path.join(FIX, s + suffix), "w", encoding="utf-8", newline="\n") as fh:
            json.dump(doc, fh, indent=1, sort_keys=True)
            fh.write("\n")
    return s


