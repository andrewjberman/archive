def sh(args, cwd=None, timeout=300):
    # explicit utf-8 (errors='replace'): this device's locale.getpreferredencoding() is cp1252, and
    # subprocess.run(text=True) with no `encoding=` decodes through THAT -- a real UTF-8 byte such as
    # the em-dash (\xe2\x80\x94) then mis-decodes to a 3-character mojibake string while the BYTES on
    # disk are untouched (measured: git cat-file -p piped through cp1252 vs the same blob read as
    # utf-8 disagree on the SAME bytes). Every git/terraform/python subprocess call in this battery
    # goes through here so this fix is estate-wide within the battery, not per call-site.
    p = subprocess.run(args, cwd=cwd or REPO, capture_output=True, timeout=timeout)
    out = p.stdout.decode("utf-8", errors="replace")
    err = p.stderr.decode("utf-8", errors="replace")
    return p.returncode, out, err


def git(*args, cwd=None):
    return sh(["git"] + list(args), cwd=cwd)


def git_blob(blob) -> str:
    rc, out, err = git("cat-file", "-p", blob)
    if rc != 0:
        raise RuntimeError("git cat-file -p %s failed: %s" % (blob, err))
    return out


def write_text(path: Path, text: str):
    path.parent.mkdir(parents=True, exist_ok=True)
    path.write_text(text, encoding="utf-8", newline="\n")


