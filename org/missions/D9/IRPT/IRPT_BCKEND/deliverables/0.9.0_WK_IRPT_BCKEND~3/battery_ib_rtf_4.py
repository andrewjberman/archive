def list_all_paths():
    rc, out, _ = git("ls-files", "-z")
    tracked = set(out.split("\0")) if rc == 0 else set()
    rc2, out2, _ = git("ls-files", "-z", "--others", "--exclude-standard")
    untracked = set(out2.split("\0")) if rc2 == 0 else set()
    paths = sorted(p for p in (tracked | untracked) if p)
    return paths


def canonical_targets():
    rc, out, err = sh([PY, "-3.12", "lib/opal_naming.py", "targets"], timeout=60)
    assert rc == 0, "opal_naming.py targets failed: %s" % err
    rows = []
    for kind, plane, path in TARGET_LINE_RE.findall(out):
        rows.append({"kind": kind, "plane": plane, "path": path})
    return rows, out


def arm_a_census():
    print("\n==== ARM (a): CENSUS OF GENERATED TARGETS, UNSCOPED ====")
    targets, targets_raw = canonical_targets()
    canonical_paths = {t["path"] for t in targets}
    print("Builder's own `targets` self-report (%d canonical targets):" % len(targets))
    print(targets_raw.strip())

    all_paths = list_all_paths()
    print("\nUnscoped sweep: %d tracked+untracked-not-ignored paths in the tree." % len(all_paths))

    stamp_hits = []  # (path, lineno, hash)
    scanned = 0
    skipped_binary = 0
    needle = b"GENERATED by lib/opal_naming.py from infra/logic/registry@"
    for rel in all_paths:
        p = REPO / rel
        if not p.is_file():
            continue
        try:
            data = p.read_bytes()
        except OSError:
            continue
        scanned += 1
        if needle not in data:
            continue
        try:
            text = data.decode("utf-8")
        except UnicodeDecodeError:
            skipped_binary += 1
            continue
        for i, line in enumerate(text.splitlines(), start=1):
            m = STAMP_RE.search(line)
            if m:
                stamp_hits.append((rel, i, m.group(1)))

    print("\nFiles scanned: %d, skipped (undecodable as utf-8 despite carrying the needle): %d"
          % (scanned, skipped_binary))
    print("STAMP CENSUS: %d hash-bearing 'GENERATED by lib/opal_naming.py ...' blocks in %d distinct files"
          % (len(stamp_hits), len({h[0] for h in stamp_hits})))

    canonical_hits = [h for h in stamp_hits if h[0] in canonical_paths]
    historical_hits = [h for h in stamp_hits if h[0] not in canonical_paths]

    print("\n-- LIVE CODE TARGETS (match the builder's own `targets` self-report): %d block(s) in %d file(s) --"
          % (len(canonical_hits), len({h[0] for h in canonical_hits})))
    for rel, lineno, h in sorted(canonical_hits):
        grant = "IN-GRANT" if rel in IN_GRANT_TARGETS else "OUT-OF-GRANT"
        print("  %s:%d  registry@%s  [%s]" % (rel, lineno, h, grant))

    print("\n-- HISTORICAL/RECORD occurrences (mission-tree docs, patches, fixtures, prior deliverables; "
          "NOT a live regenerable target): %d block(s) in %d file(s) --"
          % (len(historical_hits), len({h[0] for h in historical_hits})))
    for rel in sorted({h[0] for h in historical_hits}):
        print("  %s" % rel)

    missing_canonical = canonical_paths - {h[0] for h in canonical_hits}
    if missing_canonical:
        print("\nWARN: canonical target(s) with no stamp match found by the sweep: %s" % sorted(missing_canonical))

    return {
        "targets": targets,
        "canonical_paths": canonical_paths,
        "canonical_hits": canonical_hits,
        "historical_hits": historical_hits,
        "all_paths_count": len(all_paths),
        "scanned": scanned,
    }


