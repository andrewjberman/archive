def _tf(args, cwd=None, timeout=300):
    return sh([str(TF_BIN)] + args, cwd=cwd or TF_DIR, timeout=timeout)


def _plan_summary(text):
    m = re.search(r"Plan: (\d+) to add, (\d+) to change, (\d+) to destroy\.", text)
    tainted = sorted(re.findall(r"# (\S+) is tainted, so must be replaced", text))
    return {
        "line": m.group(0) if m else None,
        "add": int(m.group(1)) if m else None,
        "change": int(m.group(2)) if m else None,
        "destroy": int(m.group(3)) if m else None,
        "tainted": tainted,
    }


