#!/usr/bin/env bash
# MX-s-11 AC1 (the pin is a GENERATED view, not hand-kept): data/black_diamond/scripts/bronze/_asset_dim_rest_pin.py
# carries the opal_naming MARK, and `opal_naming generate --target <pin>` reproduces it byte for byte once the
# registry@<h16> token is masked (the h16 moves whenever the registry moves; the body must not).
. "$(dirname "$0")/_root.sh"
PIN=data/black_diamond/scripts/bronze/_asset_dim_rest_pin.py
[ -f "$PIN" ] || { echo "mark present=no body identical on regeneration=no ($PIN absent) -- RESULT: FAIL"; exit 1; }
mark=no; grep -q 'GENERATED by lib/opal_naming.py from' "$PIN" && mark=yes
t=$(mktemp -d)
gen=$(timeout 90 python lib/opal_naming.py generate --out "$(native "$t")" --target "$PIN" 2>&1 | tr -d '\r'); grc=$?
same=no
if [ "$grc" = 0 ] && [ -f "$t/$PIN" ]; then
  m1=$(sed -E 's/registry@[0-9a-f]{16}/registry@H16/' "$PIN" | tr -d '\r' | sha256sum | cut -c1-64)
  m2=$(sed -E 's/registry@[0-9a-f]{16}/registry@H16/' "$t/$PIN" | tr -d '\r' | sha256sum | cut -c1-64)
  [ "$m1" = "$m2" ] && same=yes
fi
echo "mark present=$mark body identical on regeneration=$same (generate rc=$grc)"
[ "$grc" = 0 ] || printf '%s\n' "$gen" | tail -3
if [ "$mark" = yes ] && [ "$same" = yes ]; then echo "RESULT: PASS"; exit 0; fi
echo "RESULT: FAIL"; exit 1
