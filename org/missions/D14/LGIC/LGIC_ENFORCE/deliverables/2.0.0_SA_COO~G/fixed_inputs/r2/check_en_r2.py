def tf_map_in(obj, path="$"):
    """The path of the first mapping with at least 20 keys starting 'aws_' (the Terraform-type map), or None."""
    if isinstance(obj, dict):
        if sum(1 for k in obj if isinstance(k, str) and k.startswith("aws_")) >= 20:
            return path
        for k, v in obj.items():
            r = tf_map_in(v, path + "." + str(k))
            if r:
                return r
    elif isinstance(obj, list):
        for i, v in enumerate(obj):
            r = tf_map_in(v, "%s[%d]" % (path, i))
            if r:
                return r
    return None


def aws_dict_literals(path):
    """How many dict literals in a Python file carry at least 10 string keys starting 'aws_'."""
    t = read(path)
    if t is None:
        return -1
    n = 0
    for node in ast.walk(ast.parse(t)):
        if isinstance(node, ast.Dict):
            if sum(1 for k in node.keys if isinstance(k, ast.Constant) and isinstance(k.value, str) and k.value.startswith("aws_")) >= 10:
                n += 1
    return n


