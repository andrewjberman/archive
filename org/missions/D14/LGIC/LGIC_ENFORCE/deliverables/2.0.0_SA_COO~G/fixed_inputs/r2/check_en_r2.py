def _validate_commit(commit):
    root = tempfile.mkdtemp(prefix="check_en_r2_at_")
    rc, out = git("ls-tree", "--name-only", str(commit), REG + "/")
    files = [OPAL, SCHEMA, DIRECTIVES] + [p for p in out.splitlines() if p.endswith(".json")]
    for p in files:
        b = git_bytes("%s:%s" % (commit, p))
        if b is None:
            return None
        dst = os.path.join(root, *p.split("/"))
        os.makedirs(os.path.dirname(dst), exist_ok=True)
        with open(dst, "wb") as fh:
            fh.write(b)
    return validate_at(root)


