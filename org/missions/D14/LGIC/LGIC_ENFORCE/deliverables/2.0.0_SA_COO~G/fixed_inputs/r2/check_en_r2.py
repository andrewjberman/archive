def reg_files(reg_dir=REG):
    return sorted(n for n in os.listdir(reg_dir) if n.endswith(".json")) if os.path.isdir(reg_dir) else []


def hash_over(files, reg_dir=REG):
    """sha256 over the named registry files in name order, fed as name + newline + bytes, CRLF read as LF."""
    h = hashlib.sha256()
    for name in sorted(files):
        h.update(name.encode("utf-8") + b"\n")
        with open(os.path.join(reg_dir, name), "rb") as fh:
            h.update(fh.read().replace(b"\r\n", b"\n"))
    return h.hexdigest()


def temp_repo(extra=()):
    """A scratch copy of what lib/opal_naming.py reads (itself, the schema, DIRECTIVES.yaml, the registry), plus
    `extra` files or directories, laid out at their repo-relative paths. The module derives its root from its own
    path, so a copy loaded from here reads only the copy."""
    root = tempfile.mkdtemp(prefix="check_en_r2_")
    for p in [OPAL, SCHEMA, DIRECTIVES] + [REG + "/" + n for n in reg_files()] + list(extra):
        dst = os.path.join(root, *p.split("/"))
        if os.path.isdir(p):
            if not os.path.isdir(dst):
                shutil.copytree(p, dst)
            continue
        if os.path.isfile(p):
            os.makedirs(os.path.dirname(dst), exist_ok=True)
            shutil.copyfile(p, dst)
    return root


def edit_json(path, fn):
    with open(path, "rb") as fh:
        obj = json.loads(fh.read().decode("utf-8"))
    fn(obj)
    with open(path, "w", encoding="utf-8", newline="\n") as fh:
        fh.write(json.dumps(obj, indent=1) + "\n")


