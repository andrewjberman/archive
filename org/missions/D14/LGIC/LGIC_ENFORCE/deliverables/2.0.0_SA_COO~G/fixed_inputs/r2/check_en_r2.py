def say(verdict, *lines):
    for ln in lines:
        print(ln)
    print("VERDICT: " + verdict)
    sys.exit(0 if verdict.startswith("PASS-") else 1)


def read(path):
    """The file's text with CRLF read as LF, or None when it is absent."""
    if not os.path.isfile(path):
        return None
    with open(path, "rb") as fh:
        return fh.read().decode("utf-8", "replace").replace("\r\n", "\n")


def fenced_json(path):
    """The FIRST ```json fence of a record, parsed; None when the file or the fence is absent or broken."""
    t = read(path)
    if t is None:
        return None
    m = re.search(r"```json\n(.*?)\n```", t, re.S)
    if not m:
        return None
    try:
        return json.loads(m.group(1))
    except ValueError:
        return None


def load_json(path):
    t = read(path)
    if t is None:
        return None
    try:
        return json.loads(t)
    except ValueError:
        return None


def run(cmd, cwd=None, env=None, timeout=110):
    e = dict(os.environ)
    if env:
        e.update(env)
    try:
        p = subprocess.run(cmd, cwd=cwd, env=e, capture_output=True, text=True, timeout=timeout)
        return p.returncode, (p.stdout or "") + (p.stderr or "")
    except subprocess.TimeoutExpired:
        return 124, "TIMEOUT after %ds" % timeout
    except OSError as exc:
        return 127, "NOT RUNNABLE: %s" % exc


def git(*args):
    return run(["git"] + list(args))


def git_bytes(ref_path):
    """`git show <ref>:<path>` as raw bytes, or None when the object is absent."""
    p = subprocess.run(["git", "show", ref_path], capture_output=True)
    return p.stdout if p.returncode == 0 else None


def load_module(path, modname, extra_path=None):
    if not os.path.isfile(path):
        raise FileNotFoundError(path)
    added = []
    for p in ([extra_path] if extra_path else []) + [os.path.dirname(os.path.abspath(path))]:
        if p and p not in sys.path:
            sys.path.insert(0, p)
            added.append(p)
    try:
        loader = importlib.machinery.SourceFileLoader(modname, path)
        spec = importlib.util.spec_from_loader(modname, loader)
        mod = importlib.util.module_from_spec(spec)
        loader.exec_module(mod)
        return mod
    finally:
        for p in added:
            if p in sys.path:
                sys.path.remove(p)


