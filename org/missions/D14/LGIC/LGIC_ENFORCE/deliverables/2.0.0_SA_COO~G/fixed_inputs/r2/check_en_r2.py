def _firm_forms_reads(path=OPAL):
    """(reads, mentions) of firm_forms in a python file, by line: a read is any NAME token or non-docstring string
    constant that names it; a comment or docstring mention is printed and never a read. (None, None) when absent."""
    t = read(path)
    if t is None:
        return None, None
    try:
        tree = ast.parse(t)
    except SyntaxError:
        return None, None
    docs = set()
    for node in ast.walk(tree):
        if isinstance(node, (ast.Module, ast.FunctionDef, ast.AsyncFunctionDef, ast.ClassDef)) and node.body:
            first = node.body[0]
            if isinstance(first, ast.Expr) and isinstance(getattr(first, "value", None), ast.Constant) \
                    and isinstance(first.value.value, str):
                docs.add(first.lineno)
    reads, mentions = [], []
    for tok in tokenize.generate_tokens(io.StringIO(t).readline):
        if "firm_forms" not in tok.string:
            continue
        if tok.type == tokenize.NAME or (tok.type == tokenize.STRING and tok.start[0] not in docs):
            reads.append(tok.start[0])
        else:
            mentions.append(tok.start[0])
    return reads, mentions


