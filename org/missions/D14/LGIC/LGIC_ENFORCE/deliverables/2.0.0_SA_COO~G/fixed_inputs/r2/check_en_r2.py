def _fence_block(text):
    lines = (text or "").splitlines()
    i = next((k for k, ln in enumerate(lines) if re.match(r"\s*fence_patterns\s*=\s*\{", ln)), -1)
    if i < 0:
        return ""
    depth, out = 0, []
    for ln in lines[i:]:
        depth += ln.count("{") - ln.count("}")
        out.append(ln)
        if depth <= 0:
            break
    return "\n".join(out)


