#!/usr/bin/env python
"""WP3-1 AC5 -- GENERATE the battery manifest from the census, and CHECK it can fail.

⛔ GENERATED, NEVER TRANSCRIBED. The manifest is written from arm_census.py's output at a cited
commit. A hand-copied manifest beside a derived census is the typed-beside-derived defect one file
over (R3-CRO-21 / R3-DT-8) -- the census would move and the manifest would keep the old ids while
reading as authoritative.

⛔ THE CHECK MUST BE ABLE TO FAIL. `--check` compares the manifest against a FRESH census at the
manifest's own recorded commit and reports what it COUNTED. `--check --plant-missing <id>` drops
one id from the comparison set to prove the check discriminates -- a checker that has never been
seen to fail is a checker with no demonstrated failing state.
"""
import json
import os
import subprocess
import sys

HERE = os.path.dirname(os.path.abspath(__file__))
CENSUS = os.path.join(HERE, "arm_census.py")
MANIFEST = os.path.join(HERE, "MANIFEST.json")


def census_at(commit):
    out = subprocess.check_output([sys.executable, CENSUS, commit], stderr=subprocess.PIPE)
    return json.loads(out.decode("utf-8", "replace"))


def build(commit):
    c = census_at(commit)
    entries = {}
    for row, v in c["rows"].items():
        entries[row] = {"reject_ids": v["reject_ids"], "accept_ids": v["accept_ids"]}
    doc = {
        "$comment": ("GENERATED by build_manifest.py from arm_census.py at the commit named in "
                     "derived_at. Never hand-edit: re-run it. Every count a consumer needs is "
                     "COUNTED from entries, never stored as a number."),
        "derived_at": commit,
        "source": "org/standards/isck/WP3_LEDGER_DESIGN.md sec 3",
        "predicate": ("every backtick L- token in a row is one arm; `x N` expands to N; a token "
                      "cited twice in one cell counts once; rows split on UNESCAPED pipes only"),
        "entries": entries,
    }
    with open(MANIFEST, "w", encoding="utf-8", newline="\n") as fh:
        json.dump(doc, fh, indent=2, sort_keys=True)
        fh.write("\n")
    ids = [i for v in entries.values() for i in v["reject_ids"] + v["accept_ids"]]
    print("WROTE %s -- COUNTED %d rows, %d arm entries, %d distinct ids, derived at %s"
          % (os.path.relpath(MANIFEST), len(entries), len(ids), len(set(ids)), commit))


def check(plant_missing=None):
    with open(MANIFEST, "r", encoding="utf-8") as fh:
        doc = json.load(fh)
    commit = doc["derived_at"]
    fresh = census_at(commit)
    man_ids, cen_ids = [], []
    for row, v in doc["entries"].items():
        man_ids += v["reject_ids"] + v["accept_ids"]
    for row, v in fresh["rows"].items():
        cen_ids += v["reject_ids"] + v["accept_ids"]
    if plant_missing:
        man_ids = [i for i in man_ids if i != plant_missing]
    missing = sorted(set(cen_ids) - set(man_ids))
    extra = sorted(set(man_ids) - set(cen_ids))
    ok = not missing and not extra and len(man_ids) == len(cen_ids)
    print("CHECK at %s -- COUNTED manifest %d arms / census %d arms; missing %d; extra %d"
          % (commit, len(man_ids), len(cen_ids), len(missing), len(extra)))
    for i in missing:
        print("   MISSING from the manifest:", i)
    for i in extra:
        print("   EXTRA in the manifest:", i)
    print("RESULT:", "VALID" if ok else "INVALID")
    return ok


def main():
    if "--check" in sys.argv:
        plant = None
        if "--plant-missing" in sys.argv:
            plant = sys.argv[sys.argv.index("--plant-missing") + 1]
            print("NEGATIVE CONTROL: dropping %r from the manifest side -- the check MUST report "
                  "INVALID, or it cannot discriminate." % plant)
        sys.exit(0 if check(plant) else 1)
    build(sys.argv[1])


if __name__ == "__main__":
    main()
