#!/usr/bin/env python3
"""
O4 -- hygiene report surface (NFRA_EXPAND Strand-C, HEATMAP_OBJECT). The last object leg.

The human-facing render over O3's RECOMMEND/HOLD assessment. Makes the whole HEATMAP_OBJECT build
USABLE: a ranked, evidence-carrying hygiene report a human reviews. It NEVER acts and NEVER
flatly says "delete these" -- it classifies and surfaces, the human decides.

COO-steer (2026-06-25): RECOMMENDs are NOT uniform. Split them:
  - AUDIT-TRAIL class -- agent/dated log dirs (path under .../logs/...). Name-clean, BUT likely an
    intentional audit trail; retention is a POLICY call (a future Andrew/governance question).
    Surfaced, NOT pre-judged as archive-me.
  - ORPHANED-ARCHIVE class -- genuinely-dead dated archives (deck tests, cost_analysis, old
    artifacts) with no references. The actionable-after-graph-gate list.
  - HELD -- cold but REFERENCED (the footgun class O3 caught). Shown so the reviewer sees WHY a
    dead-looking dir is load-bearing.

ADVISORY-ONLY. Inherits the full chain: O3's name-vs-edge + the cited comp-blast graph gate +
never-auto-delete. Every RECOMMEND still requires the graph gate + human review before any archive.

Usage:
    python object_report.py [--root .] [--all] [--from-json O3.json] [--out report.md]
    # --from-json renders a prior O3 scan (fast); else runs O3 live (--all = full, slow).
Author: 0.4.0_DS_ClientPlatform (NFRA_EXPAND Strand-C, leg O4). 2026-06-25.
"""

from __future__ import annotations

import argparse
import json
import os
import sys
import time

sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
from heat_map import HeatParams  # noqa: E402
from object_freshness import build  # noqa: E402
from object_locality import aggregate_tree, maximal_cold_subtrees  # noqa: E402
from object_recommend import assess  # noqa: E402

AUDIT_TRAIL_MARKERS = ("/logs/",)   # agent/dated log dirs -- retention is a policy call


def _is_audit_trail(d: str) -> bool:
    p = "/" + d + "/"
    return any(m in p for m in AUDIT_TRAIL_MARKERS)


def classify(recommend: list[dict]) -> tuple[list[dict], list[dict]]:
    audit = [r for r in recommend if _is_audit_trail(r["dir"])]
    orphaned = [r for r in recommend if not _is_audit_trail(r["dir"])]
    return orphaned, audit


def render_md(recommend: list[dict], hold: list[dict], root: str, scoped: str) -> str:
    orphaned, audit = classify(recommend)
    L: list[str] = []
    L.append("# HEATMAP_OBJECT -- estate hygiene report (ADVISORY-ONLY)\n")
    L.append(f"- root: `{root}` - scope: {scoped} - generated by O4 (NFRA_EXPAND Strand-C)")
    L.append("- **ADVISORY ONLY. Nothing here is auto-archived.** Every RECOMMEND still requires "
             "the `comp-blast` graph gate + human review before any action. *cold != safe.*\n")
    L.append(f"**Summary:** {len(orphaned)} orphaned-archive candidate(s) - "
             f"{len(audit)} audit-trail candidate(s) [policy call] - "
             f"{len(hold)} held (cold but referenced).\n")

    L.append("## 1. Orphaned-archive candidates (name-clean, non-log) -- review + graph-gate, then archive")
    if not orphaned:
        L.append("_none_")
    for r in sorted(orphaned, key=lambda r: -r["n_cold"]):
        L.append(f"- `{r['dir']}/` -- {r['n_cold']} cold files, oldest {r['oldest_age_days']:.0f}d. "
                 f"GATE before acting: `{r['mandatory_graph_gate']}`")

    L.append("\n## 2. Audit-trail candidates (name-clean BUT logs) -- RETENTION IS A POLICY CALL, not archive-me")
    L.append("_These are agent/dated log dirs. Name-clean, but likely an intentional audit trail. "
             "Surfaced for a retention-policy decision (future governance) -- DO NOT flatly archive._")
    if not audit:
        L.append("_none_")
    for r in sorted(audit, key=lambda r: -r["n_cold"])[:40]:
        L.append(f"- `{r['dir']}/` -- {r['n_cold']} cold files, oldest {r['oldest_age_days']:.0f}d")
    if len(audit) > 40:
        L.append(f"- _... and {len(audit) - 40} more audit-trail dirs_")

    L.append("\n## 3. Held -- cold but REFERENCED (NOT archive candidates; the verify-before-recommend catch)")
    for r in sorted(hold, key=lambda r: -r["n_cold"])[:25]:
        refs = ", ".join(f"`{x}`" for x in r["inbound_refs"][:3])
        L.append(f"- `{r['dir']}/` -- {r['n_cold']} cold, ref'd by: {refs}")
    if len(hold) > 25:
        L.append(f"- _... and {len(hold) - 25} more held (referenced) dirs_")
    return "\n".join(L) + "\n"


def main() -> int:
    ap = argparse.ArgumentParser(description="O4 hygiene report surface over O3")
    ap.add_argument("--root", default=".")
    ap.add_argument("--from-json", default="", help="render a prior O3 --json scan (fast)")
    ap.add_argument("--all", action="store_true", help="run O3 live over ALL cold subtrees (slow)")
    ap.add_argument("--top", type=int, default=40)
    ap.add_argument("--out", default="", help="write the markdown report to this path")
    args = ap.parse_args()
    root = os.path.abspath(args.root)

    if args.from_json:
        with open(args.from_json, encoding="utf-8") as fh:
            d = json.load(fh)
        recommend, hold = d["recommend"], d["hold"]
        scoped = f"from O3 scan {os.path.basename(args.from_json)}"
    else:
        scores, _ = build(root, HeatParams(), time.time())
        cold = maximal_cold_subtrees(aggregate_tree(scores))
        candidates = cold if args.all else cold[:args.top]
        assessed = assess(root, candidates)
        recommend = [a for a in assessed if a["verdict"] == "RECOMMEND_ARCHIVE"]
        hold = [a for a in assessed if a["verdict"] == "HOLD_REFERENCED"]
        scoped = "all cold subtrees" if args.all else f"top {args.top} cold subtrees"

    orphaned, audit = classify(recommend)
    print("=== O4 hygiene report (ADVISORY-ONLY -- never auto-archives) ===")
    print(f"  {len(orphaned)} orphaned-archive | {len(audit)} audit-trail [policy] | {len(hold)} held(ref'd)")
    print("  orphaned-archive (top, gate-then-archive):")
    for r in sorted(orphaned, key=lambda r: -r["n_cold"])[:10]:
        print(f"    {r['n_cold']:5d} cold  {r['oldest_age_days']:.0f}d  {r['dir']}/")
    print(f"  audit-trail [retention=policy call, NOT archive-me]: {len(audit)} dirs "
          f"(e.g. {', '.join(r['dir'] for r in audit[:2])})")

    if args.out:
        with open(args.out, "w", encoding="utf-8") as fh:
            fh.write(render_md(recommend, hold, root, scoped))
        print(f"OK: wrote hygiene report -> {args.out}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
