#!/usr/bin/env python3
"""pipescript <name> -- named-thread estate traversal (NFRA_PIPESCRIPT P1).

One human entry point: `pipescript news` -> every resource in that named thread +
its producers -> served artifacts -> frontend consumers + owning tool + coverage
status + debt flags. No silent Unknown: an unknown name or an unowned-tool query
is always LOUD (exit 2).

Module form of the COO-driven reference CLI (714837b5e), hardened to the comp-*
convention: thin `.tools/pipescript` bash wrapper -> this module -> comp_log_auto.py
logging, registered in graph-call-manifest.yaml. The owning-tool routing-DISPATCH to
each sub-resolver (comp-pipescript io/deployed medallion / globgrph AWS-resource /
stitch cross-layer / portal-consumer-tools frontend) is P1b.

Resolver backend: org/modules/graph/estate-coverage-resolver.json (generated by
gen-estate-resolver.py from CVO's AUTHORITATIVE estate-coverage-manifest 61e91d334 +
the census per-thread detail; owning_tool per CTO's ratified medallion-only boundary,
NOT a heuristic). Read-only.

Usage:
    pipescript <name>                 # one named thread's full traversal
    pipescript --list                 # the named threads + coverage counts
    pipescript --resource <substr>    # reverse lookup: which thread references <substr>
    pipescript --tool <name> <tool>   # GUARD: LOUD OUT-OF-SCOPE + exit 2 if <tool>
                                      #        owns nothing in named thread <name>
    pipescript --validate             # completeness gate (every thread -> 1 named thread)
"""
from __future__ import annotations

import json
import os
import sys
from collections import Counter, defaultdict

ROOT = os.path.dirname(os.path.dirname(os.path.dirname(os.path.dirname(os.path.abspath(__file__)))))
RESOLVER = os.path.join(ROOT, "org", "modules", "graph", "estate-coverage-resolver.json")

OWNING_TOOLS = {
    "comp-pipescript": "comp-pipescript io/deployed/postdeps (medallion data-pipeline)",
    "globgrph": "comp-kuzu / comp-aws (AWS-resource graph)",
    "stitch": "comp-stitch (cross-layer)",
    "portal-consumer-tools": "comp-transform / comp-routes (frontend reachability)",
    "none": "(ops/local - explicit-out, no owning tool)",
}

# The resolver/census payload can carry non-ASCII (em/en dash, smart quotes) inherited
# from upstream docs. Stdout MUST be ASCII-only (CLAUDE.md: non-ASCII breaks charmap/
# grep/CI). _a() transliterates the common cases + drops any residual so a named-thread
# traversal is always clean ASCII regardless of source-data drift.
_NONASCII = {
    0x2014: "-", 0x2013: "-",      # em / en dash
    0x2018: "'", 0x2019: "'",      # smart single quotes
    0x201C: '"', 0x201D: '"',      # smart double quotes
    0x2022: "-", 0x2026: "...",    # bullet, ellipsis
    0x00A0: " ",                   # non-breaking space
}


def _a(s):
    if not s:
        return s
    # str.translate maps codepoints -> ASCII; the encode backstop drops any residual
    return s.translate(_NONASCII).encode("ascii", "replace").decode("ascii")


def load():
    try:
        with open(RESOLVER, encoding="utf-8") as f:
            return json.load(f)
    except FileNotFoundError:
        sys.stderr.write(
            f"ERROR: resolver not found at {RESOLVER}\n"
            f"  -> run org/modules/graph/gen-estate-resolver.py to (re)generate it.\n"
        )
        sys.exit(3)


def status_tag(s):
    return {
        "in-scope": "in-scope    ",
        "explicit-out": "explicit-out",
        "unreviewed": "UNREVIEWED  ",
    }.get(s, s)


def cmd_list(data):
    threads = data["threads"]
    by_name = defaultdict(list)
    for t in threads:
        by_name[t["named_thread"]].append(t)
    print(
        f"pipescript - {len(data['named_threads'])} named threads / {len(threads)} sub-threads "
        f"(estate census {data.get('last_review', '')})"
    )
    print("=" * 78)
    print("Usage: pipescript <name>   |   pipescript --resource <substr>   |   pipescript --validate")
    print()
    print(f"{'NAME':<20} {'THREADS':>7}  {'IN-SCOPE':>8} {'OUT':>4} {'UNREV':>5}  TOOLS")
    print("-" * 78)
    for name in data["named_threads"]:
        ts = by_name[name]
        sc = Counter(t["status"] for t in ts)
        tools = ",".join(sorted({t["owning_tool"] for t in ts}))
        print(
            f"{name:<20} {len(ts):>7}  {sc.get('in-scope', 0):>8} {sc.get('explicit-out', 0):>4} "
            f"{sc.get('unreviewed', 0):>5}  {tools}"
        )
    print("-" * 78)
    print(f"{'TOTAL':<20} {len(threads):>7}")


def cmd_thread(data, name):
    threads = [t for t in data["threads"] if t["named_thread"] == name]
    if not threads:
        # LOUD unknown name - never a silent empty result
        sys.stderr.write(f"pipescript: '{name}' is NOT a known named thread.\n")
        sys.stderr.write(f"  -> known threads: {', '.join(data['named_threads'])}\n")
        sys.stderr.write("  -> run `pipescript --list` for counts.\n")
        sys.exit(2)
    sc = Counter(t["status"] for t in threads)
    tc = Counter(t["owning_tool"] for t in threads)
    print(
        f"pipescript {name} - {len(threads)} threads "
        f"(in-scope {sc.get('in-scope', 0)} / explicit-out {sc.get('explicit-out', 0)} / "
        f"unreviewed {sc.get('unreviewed', 0)})"
    )
    print("=" * 78)
    for t in threads:
        flags = (" flags=" + ",".join(t["debtscan_flags"])) if t["debtscan_flags"] else ""
        print(f"\n[{status_tag(t['status'])} | {t['owning_tool']}] {_a(t['thread_id'])}{flags}")
        if t.get("description"):
            print(f"  what: {_a(t['description'])}")
        for i, p in enumerate(t.get("producers") or ["(none recorded)"]):
            print(f"  {'producers:' if i == 0 else '          '} {_a(p)}")
        for i, s in enumerate(t.get("served_artifacts") or ["(no data artifact)"]):
            print(f"    {'-> served:' if i == 0 else '          '} {_a(s)}")
        fe = _a(t.get("frontend_resolution") or "(none)")
        print(f"    -> frontend: {fe}")
    print("\n" + "-" * 78)
    print("owning tools in this thread:")
    for tool, n in tc.most_common():
        print(f"  {n:>3}  {tool:<22} {OWNING_TOOLS.get(tool, '')}")
    print("\nrun `pipescript --tool <name> <tool>` to assert a tool owns it (LOUD OUT-OF-SCOPE if not).")


def cmd_resource(data, needle):
    needle_l = needle.lower()
    hits = []
    for t in data["threads"]:
        blob = " ".join(
            [
                t["thread_id"],
                t.get("description", ""),
                " ".join(t.get("producers") or []),
                " ".join(t.get("served_artifacts") or []),
                t.get("frontend_resolution", "") or "",
            ]
        ).lower()
        if needle_l in blob:
            hits.append(t)
    if not hits:
        sys.stderr.write(f"pipescript: no thread references '{needle}'.\n")
        sys.exit(2)
    print(f"pipescript --resource '{needle}' -> {len(hits)} thread(s):")
    for t in hits:
        print(f"  {t['named_thread']:<18} / {t['thread_id']:<32} [{t['status']} | {t['owning_tool']}]")


def cmd_tool(data, name, tool):
    """Guard contract: assert `tool` owns threads under `name`; LOUD OUT-OF-SCOPE if not.

    Hardened to emit the canonical TOOL-02 false-clean string
    'OUT-OF-SCOPE for {tool} -> see {owning_tool}' + exit 2 -- the generalized guard
    every sub-resolver fires in P1b so an unowned-tool query is never silent-clean.
    """
    if tool not in OWNING_TOOLS:
        sys.stderr.write(
            f"pipescript: '{tool}' is not a known owning_tool. "
            f"Known: {', '.join(sorted(OWNING_TOOLS))}.\n"
        )
        sys.exit(2)
    threads = [t for t in data["threads"] if t["named_thread"] == name]
    if not threads:
        sys.stderr.write(f"pipescript: '{name}' is NOT a known named thread (see --list).\n")
        sys.exit(2)
    owned = [t for t in threads if t["owning_tool"] == tool]
    if not owned:
        tools = sorted({t["owning_tool"] for t in threads})
        # canonical false-clean guard string (exit 2) -- never a silent empty result
        sys.stderr.write(
            f"OUT-OF-SCOPE for {tool} -> see {'/'.join(tools)} "
            f"(named thread '{name}' is owned by {', '.join(tools)}, not {tool})\n"
        )
        sys.exit(2)
    print(f"{tool} owns {len(owned)}/{len(threads)} threads in '{name}':")
    for t in owned:
        print(f"  {t['thread_id']} [{t['status']}]")


def cmd_validate(data):
    """Completeness gate: every census resource -> exactly one named thread; no orphan."""
    threads = data["threads"]
    ids = [t["thread_id"] for t in threads]
    dup = [x for x in set(ids) if ids.count(x) > 1]
    names = set(data["named_threads"])
    unbucketed = [t["thread_id"] for t in threads if t["named_thread"] not in names]
    ok = True
    print("pipescript --validate (NFRA_PIPESCRIPT acceptance)")
    print("=" * 60)
    print(f"  total sub-threads:        {len(threads)}")
    print(f"  named threads:            {len(names)}")
    print(f"  duplicate thread_ids:     {len(dup)} {dup if dup else ''}")
    print(f"  threads w/o named bucket: {len(unbucketed)} {unbucketed if unbucketed else ''}")
    if dup or unbucketed:
        ok = False
    sc = Counter(t["status"] for t in threads)
    print(f"  status: {dict(sc)}")
    unrev = [t["thread_id"] for t in threads if t["status"] == "unreviewed"]
    print(f"  UNREVIEWED (need owner-confirm, not inherit-clean): {len(unrev)}")
    print("-" * 60)
    print(
        "RESULT:",
        "PASS - every thread resolves to exactly one named thread, no orphan/dup"
        if ok
        else "FAIL - see above",
    )
    sys.exit(0 if ok else 1)


def main(argv):
    data = load()
    if not argv or argv[0] in ("-h", "--help"):
        cmd_list(data)
        return 0
    if argv[0] == "--list":
        cmd_list(data)
        return 0
    if argv[0] == "--validate":
        cmd_validate(data)
        return 0
    if argv[0] == "--resource":
        if len(argv) < 2:
            sys.stderr.write("usage: pipescript --resource <substr>\n")
            sys.exit(3)
        cmd_resource(data, argv[1])
        return 0
    if argv[0] == "--tool":
        if len(argv) < 3:
            sys.stderr.write("usage: pipescript --tool <name> <tool>\n")
            sys.exit(3)
        cmd_tool(data, argv[1], argv[2])
        return 0
    cmd_thread(data, argv[0])
    return 0


if __name__ == "__main__":
    sys.exit(main(sys.argv[1:]))
